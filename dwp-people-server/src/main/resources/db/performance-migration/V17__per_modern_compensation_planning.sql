CREATE FUNCTION hris_performance.prf_cmp_validate_budget_entry()
RETURNS TRIGGER AS $$
DECLARE
    source_row hris_performance.prf_cmp_budget_ledger%ROWTYPE;
    balance NUMERIC(19,4);
    cycle_state VARCHAR(40);
BEGIN
    SELECT status INTO cycle_state
      FROM hris_performance.prf_cmp_cycles
     WHERE tenant_id = NEW.tenant_id
       AND prf_cmp_cycles_internal_id = NEW.compensation_cycle_id
     FOR UPDATE;
    IF cycle_state IS NULL OR cycle_state NOT IN ('DRAFT', 'OPEN') THEN
        RAISE EXCEPTION 'PER_COMPENSATION_BUDGET_INVALID_STATE'
            USING ERRCODE = '23514';
    END IF;

    IF NEW.entry_type = 'REVERSE' THEN
        SELECT * INTO source_row
          FROM hris_performance.prf_cmp_budget_ledger
         WHERE tenant_id = NEW.tenant_id
           AND compensation_cycle_id = NEW.compensation_cycle_id
           AND public_id = NEW.source_entry_public_id
         FOR UPDATE;
        IF NOT FOUND
           OR source_row.entry_type <> 'ALLOCATE'
           OR source_row.source_entry_public_id IS NOT NULL
           OR source_row.org_public_id <> NEW.org_public_id
           OR source_row.currency_code <> NEW.currency_code
           OR source_row.amount <> NEW.amount THEN
            RAISE EXCEPTION 'PER_COMPENSATION_INVALID_REVERSAL'
                USING ERRCODE = '23514';
        END IF;
        IF EXISTS (
            SELECT 1 FROM hris_performance.prf_cmp_budget_ledger reversal
             WHERE reversal.tenant_id = NEW.tenant_id
               AND reversal.compensation_cycle_id = NEW.compensation_cycle_id
               AND reversal.entry_type = 'REVERSE'
               AND reversal.source_entry_public_id = NEW.source_entry_public_id
        ) THEN
            RAISE EXCEPTION 'PER_COMPENSATION_ALREADY_REVERSED'
                USING ERRCODE = '23505';
        END IF;
        IF EXISTS (
            SELECT 1
              FROM hris_performance.prf_cmp_proposals proposal
             WHERE proposal.tenant_id = NEW.tenant_id
               AND proposal.compensation_cycle_id = NEW.compensation_cycle_id
               AND proposal.status = 'FROZEN'
        ) OR EXISTS (
            SELECT 1
              FROM hris_performance.prf_cmp_approved_snapshots snapshot
             WHERE snapshot.tenant_id = NEW.tenant_id
               AND snapshot.compensation_cycle_id = NEW.compensation_cycle_id
        ) THEN
            RAISE EXCEPTION 'PER_COMPENSATION_BUDGET_COMMITTED'
                USING ERRCODE = '23514';
        END IF;
    END IF;

    SELECT COALESCE(SUM(
               CASE WHEN entry_type = 'ALLOCATE' THEN amount ELSE -amount END
           ), 0) INTO balance
      FROM hris_performance.prf_cmp_budget_ledger
     WHERE tenant_id = NEW.tenant_id
       AND compensation_cycle_id = NEW.compensation_cycle_id
       AND org_public_id = NEW.org_public_id
       AND currency_code = NEW.currency_code;
    IF balance + (CASE WHEN NEW.entry_type = 'ALLOCATE'
            THEN NEW.amount ELSE -NEW.amount END) < 0 THEN
        RAISE EXCEPTION 'PER_COMPENSATION_NEGATIVE_BUDGET'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY INVOKER SET search_path TO pg_catalog;

CREATE FUNCTION hris_performance.prf_cmp_validate_artifact_binding()
RETURNS TRIGGER AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
          FROM hris_performance.prf_per_artifact_versions artifact
         WHERE artifact.tenant_id = NEW.tenant_id
           AND artifact.public_id = NEW.guideline_artifact_public_id
           AND artifact.artifact_type = 'COMPENSATION_GUIDELINES'
           AND artifact.owner_aggregate_type = 'COMPENSATION_CYCLE'
           AND artifact.owner_aggregate_public_id = NEW.public_id
    ) OR NOT EXISTS (
        SELECT 1
          FROM hris_performance.prf_per_artifact_versions artifact
         WHERE artifact.tenant_id = NEW.tenant_id
           AND artifact.public_id = NEW.population_artifact_public_id
           AND artifact.artifact_type = 'COMPENSATION_POPULATION'
           AND artifact.owner_aggregate_type = 'COMPENSATION_CYCLE'
           AND artifact.owner_aggregate_public_id = NEW.public_id
    ) THEN
        RAISE EXCEPTION 'PER_COMPENSATION_ARTIFACT_BINDING_INVALID'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY INVOKER SET search_path TO pg_catalog;

