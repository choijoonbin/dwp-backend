CREATE TABLE hris_performance.prf_per_artifact_versions (
    artifact_version_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    public_id UUID NOT NULL,
    artifact_type VARCHAR(80) NOT NULL,
    schema_version INTEGER NOT NULL,
    artifact_revision BIGINT NOT NULL,
    owner_aggregate_type VARCHAR(100) NOT NULL,
    owner_aggregate_public_id UUID NOT NULL,
    canonical_content_digest CHAR(64) NOT NULL,
    encrypted_content BYTEA NOT NULL,
    encryption_key_version_public_id UUID NOT NULL,
    effective_from DATE NOT NULL,
    effective_to DATE,
    created_at TIMESTAMPTZ NOT NULL,
    created_by UUID NOT NULL,
    CONSTRAINT uk_prf_per_artifact_versions_tenant_public
        UNIQUE (tenant_id, public_id),
    CONSTRAINT uk_prf_per_artifact_versions_owner_revision
        UNIQUE (
            tenant_id, owner_aggregate_type, owner_aggregate_public_id,
            artifact_type, artifact_revision
        ),
    CONSTRAINT ck_prf_per_artifact_versions_type_schema CHECK (
        schema_version = 1
        AND artifact_type IN (
            'COMPENSATION_GUIDELINES',
            'COMPENSATION_POPULATION',
            'COMPENSATION_PROPOSAL'
        )
    ),
    CONSTRAINT ck_prf_per_artifact_versions_revision CHECK (artifact_revision > 0),
    CONSTRAINT ck_prf_per_artifact_versions_owner CHECK (
        (artifact_type IN ('COMPENSATION_GUIDELINES', 'COMPENSATION_POPULATION')
            AND owner_aggregate_type = 'COMPENSATION_CYCLE')
        OR
        (artifact_type = 'COMPENSATION_PROPOSAL'
            AND owner_aggregate_type = 'COMPENSATION_PROPOSAL_REVISION')
    ),
    CONSTRAINT ck_prf_per_artifact_versions_digest CHECK (
        canonical_content_digest ~ '^[0-9a-f]{64}$'
    ),
    CONSTRAINT ck_prf_per_artifact_versions_encrypted CHECK (
        octet_length(encrypted_content) > 28
    ),
    CONSTRAINT ck_prf_per_artifact_versions_dates CHECK (
        effective_to IS NULL OR effective_to > effective_from
    )
