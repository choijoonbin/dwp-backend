CREATE FUNCTION hris_performance.prf_cmp_validate_snapshot_lines()
RETURNS TRIGGER AS $$
DECLARE
    persisted_count INTEGER;
    minimum_sequence INTEGER;
    maximum_sequence INTEGER;
    cycle_state VARCHAR(40);
BEGIN
    SELECT COUNT(*), MIN(line_sequence), MAX(line_sequence)
      INTO persisted_count, minimum_sequence, maximum_sequence
      FROM hris_performance.prf_cmp_approved_snapshot_lines
     WHERE tenant_id = NEW.tenant_id
       AND approved_compensation_snapshot_id = NEW.prf_cmp_approved_snapshots_internal_id;
    IF persisted_count <> NEW.line_count
       OR minimum_sequence <> 1
       OR maximum_sequence <> NEW.line_count THEN
        RAISE EXCEPTION 'PER_COMPENSATION_SNAPSHOT_LINES_INCOMPLETE'
            USING ERRCODE = '23514';
    END IF;
    SELECT status INTO cycle_state
      FROM hris_performance.prf_cmp_cycles
     WHERE tenant_id = NEW.tenant_id
       AND prf_cmp_cycles_internal_id = NEW.compensation_cycle_id
     FOR UPDATE;
    IF cycle_state IS DISTINCT FROM 'PUBLISHED' THEN
        RAISE EXCEPTION 'PER_COMPENSATION_SNAPSHOT_INVALID_STATE'
            USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql SECURITY INVOKER SET search_path TO pg_catalog;

CREATE FUNCTION hris_performance.prf_cmp_guard_cycle_cas()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.tenant_id <> OLD.tenant_id
       OR NEW.prf_cmp_cycles_internal_id <> OLD.prf_cmp_cycles_internal_id
       OR NEW.public_id <> OLD.public_id
       OR NEW.created_at <> OLD.created_at
       OR NEW.created_by <> OLD.created_by
       OR NEW.cycle_code <> OLD.cycle_code
       OR NEW.aggregate_version <> OLD.aggregate_version + 1
       OR NOT (
           (OLD.status = 'DRAFT' AND NEW.status IN ('DRAFT', 'OPEN', 'CANCELLED'))
           OR (OLD.status = 'OPEN' AND NEW.status IN (
               'OPEN', 'PROPOSAL_REVIEW', 'CANCELLED'))
           OR (OLD.status = 'PROPOSAL_REVIEW' AND NEW.status IN (
               'PROPOSAL_REVIEW', 'APPROVED', 'CANCELLED'))
           OR (OLD.status = 'APPROVED' AND NEW.status = 'PUBLISHED')
       )
       OR ((OLD.status IN ('PROPOSAL_REVIEW', 'APPROVED')
               OR NEW.status IS DISTINCT FROM OLD.status)
           AND (NEW.guideline_artifact_public_id IS DISTINCT FROM
                    OLD.guideline_artifact_public_id
                OR NEW.population_artifact_public_id IS DISTINCT FROM
                    OLD.population_artifact_public_id
                OR NEW.effective_from IS DISTINCT FROM OLD.effective_from
                OR NEW.effective_to IS DISTINCT FROM OLD.effective_to)) THEN
        RAISE EXCEPTION 'PER_COMPENSATION_CYCLE_CAS_VIOLATION'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY INVOKER SET search_path TO pg_catalog;

CREATE FUNCTION hris_performance.prf_cmp_guard_proposal_cas()
RETURNS TRIGGER AS $$
DECLARE
    cycle_state VARCHAR(40);
BEGIN
    SELECT status INTO cycle_state
      FROM hris_performance.prf_cmp_cycles
     WHERE tenant_id = NEW.tenant_id
       AND prf_cmp_cycles_internal_id = NEW.compensation_cycle_id
     FOR UPDATE;
    IF cycle_state IS NULL THEN
        RAISE EXCEPTION 'PER_COMPENSATION_PROPOSAL_CAS_VIOLATION'
            USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'DRAFT' THEN
            RAISE EXCEPTION 'PER_COMPENSATION_PROPOSAL_CAS_VIOLATION'
                USING ERRCODE = '23514';
        END IF;
        RETURN NEW;
    END IF;

    IF NEW.tenant_id <> OLD.tenant_id
       OR NEW.prf_cmp_proposals_internal_id <> OLD.prf_cmp_proposals_internal_id
       OR NEW.public_id <> OLD.public_id
       OR NEW.created_at <> OLD.created_at
       OR NEW.created_by <> OLD.created_by
       OR NEW.compensation_cycle_id <> OLD.compensation_cycle_id
       OR NEW.worker_public_id <> OLD.worker_public_id
       OR NEW.assignment_public_id <> OLD.assignment_public_id
       OR NEW.supersedes_proposal_public_id IS DISTINCT FROM
            OLD.supersedes_proposal_public_id
       OR NEW.aggregate_version <> OLD.aggregate_version + 1
       OR NOT (
           (OLD.status = 'DRAFT' AND NEW.status = 'DRAFT'
               AND NEW.current_revision = OLD.current_revision + 1)
           OR (OLD.status = 'DRAFT' AND NEW.status IN ('SUBMITTED', 'CANCELLED')
               AND NEW.current_revision = OLD.current_revision
               AND NEW.component_code = OLD.component_code
               AND NEW.currency_code = OLD.currency_code
               AND NEW.amount = OLD.amount
               AND NEW.effective_from = OLD.effective_from
               AND NEW.effective_to IS NOT DISTINCT FROM OLD.effective_to)
           OR (OLD.status = 'SUBMITTED' AND NEW.status IN ('FROZEN', 'CANCELLED')
               AND NEW.current_revision = OLD.current_revision
               AND NEW.component_code = OLD.component_code
               AND NEW.currency_code = OLD.currency_code
               AND NEW.amount = OLD.amount
               AND NEW.effective_from = OLD.effective_from
               AND NEW.effective_to IS NOT DISTINCT FROM OLD.effective_to
               AND (NEW.status <> 'FROZEN' OR cycle_state = 'APPROVED'))
       ) THEN
        RAISE EXCEPTION 'PER_COMPENSATION_PROPOSAL_CAS_VIOLATION'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY INVOKER SET search_path TO pg_catalog;

CREATE FUNCTION hris_performance.prf_cmp_validate_proposal_artifact()
RETURNS TRIGGER AS $$
DECLARE
    proposal_state VARCHAR(40);
BEGIN
    SELECT status INTO proposal_state
      FROM hris_performance.prf_cmp_proposals
     WHERE tenant_id = NEW.tenant_id
       AND prf_cmp_proposals_internal_id = NEW.compensation_proposal_id
     FOR UPDATE;
    IF proposal_state IS DISTINCT FROM 'DRAFT'
       OR NOT EXISTS (
           SELECT 1
             FROM hris_performance.prf_per_artifact_versions artifact
            WHERE artifact.tenant_id = NEW.tenant_id
              AND artifact.public_id = NEW.typed_content_artifact_public_id
              AND artifact.artifact_type = 'COMPENSATION_PROPOSAL'
              AND artifact.owner_aggregate_type = 'COMPENSATION_PROPOSAL_REVISION'
              AND artifact.owner_aggregate_public_id = NEW.public_id
              AND artifact.artifact_revision = 1
              AND artifact.canonical_content_digest = NEW.content_digest
       ) THEN
        RAISE EXCEPTION 'PER_COMPENSATION_PROPOSAL_ARTIFACT_INVALID'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY INVOKER SET search_path TO pg_catalog;

CREATE FUNCTION hris_performance.prf_cmp_validate_snapshot_line_parent()
RETURNS TRIGGER AS $$
DECLARE
    expected_count INTEGER;
BEGIN
    SELECT line_count INTO expected_count
      FROM hris_performance.prf_cmp_approved_snapshots
     WHERE tenant_id = NEW.tenant_id
       AND prf_cmp_approved_snapshots_internal_id =
           NEW.approved_compensation_snapshot_id;
    IF expected_count IS NULL OR NEW.line_sequence > expected_count
       OR substring(NEW.public_id::text, 15, 1) <> '4'
       OR substring(NEW.public_id::text, 20, 1) !~ '[89ab]' THEN
        RAISE EXCEPTION 'PER_COMPENSATION_SNAPSHOT_LINE_INVALID'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY INVOKER SET search_path TO pg_catalog;

