CREATE TABLE hris_performance.prf_review_assignments (
    review_assignment_internal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    review_id UUID NOT NULL,
    participant_id UUID NOT NULL,
    reviewer_assignment_id UUID NOT NULL,
    reviewer_principal_public_id UUID NOT NULL,
    organization_public_id UUID NOT NULL,
    reviewer_type VARCHAR(32) NOT NULL,
    stage_key VARCHAR(80) NOT NULL,
    review_state VARCHAR(24) NOT NULL,
    template_version_id UUID NOT NULL,
    template_content_hash CHAR(64) NOT NULL,
    aggregate_version BIGINT NOT NULL DEFAULT 0,
    writable BOOLEAN NOT NULL DEFAULT TRUE,
    draft_content_hash CHAR(64) NOT NULL,
    form_definition JSONB NOT NULL,
    draft_answers JSONB NOT NULL DEFAULT '[]'::JSONB,
    due_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT NOT NULL,
    CONSTRAINT uk_prf_review_assignments_tenant_review
        UNIQUE (tenant_id, review_id),
    CONSTRAINT ck_prf_review_assignments_reviewer_type CHECK (
        reviewer_type IN (
            'SELF', 'MANAGER', 'SECOND_MANAGER', 'THIRD_MANAGER',
            'PEER', 'DIRECT_REPORT', 'EXTERNAL', 'REFEREE'
        )
    ),
    CONSTRAINT ck_prf_review_assignments_state CHECK (
        review_state IN (
            'NOT_STARTED', 'IN_PROGRESS', 'SUBMITTED',
            'RETURNED', 'COMPLETED', 'CANCELLED'
        )
    ),
    CONSTRAINT ck_prf_review_assignments_writable_state CHECK (
        NOT writable OR review_state IN ('NOT_STARTED', 'IN_PROGRESS', 'RETURNED')
    ),
    CONSTRAINT ck_prf_review_assignments_self_binding CHECK (
        reviewer_type <> 'SELF'
        OR reviewer_principal_public_id = participant_id
    ),
    CONSTRAINT ck_prf_review_assignments_stage CHECK (btrim(stage_key) <> ''),
    CONSTRAINT ck_prf_review_assignments_version CHECK (aggregate_version >= 0),
    CONSTRAINT ck_prf_review_assignments_hashes CHECK (
        template_content_hash ~ '^[0-9a-f]{64}$'
        AND draft_content_hash ~ '^[0-9a-f]{64}$'
    ),
    CONSTRAINT ck_prf_review_assignments_form CHECK (
        jsonb_typeof(form_definition) = 'object'
    ),
    CONSTRAINT ck_prf_review_assignments_answers CHECK (
        jsonb_typeof(draft_answers) = 'array'
        AND jsonb_array_length(draft_answers) <= 500
    )
);

CREATE TABLE hris_performance.prf_review_submissions (
    review_submission_internal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    submission_id UUID NOT NULL,
    review_id UUID NOT NULL,
    reviewer_assignment_id UUID NOT NULL,
    template_version_id UUID NOT NULL,
    template_content_hash CHAR(64) NOT NULL,
    submission_no BIGINT NOT NULL,
    content_hash CHAR(64) NOT NULL,
    submitted_answers JSONB NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL,
    submitted_by BIGINT NOT NULL,
    command_receipt_id UUID NOT NULL,
    CONSTRAINT uk_prf_review_submissions_tenant_submission
        UNIQUE (tenant_id, submission_id),
    CONSTRAINT uk_prf_review_submissions_tenant_sequence
        UNIQUE (tenant_id, review_id, submission_no),
    CONSTRAINT uk_prf_review_submissions_receipt
        UNIQUE (tenant_id, command_receipt_id),
    CONSTRAINT fk_prf_review_submissions_assignment FOREIGN KEY (
        tenant_id, review_id
    ) REFERENCES hris_performance.prf_review_assignments (
        tenant_id, review_id
    ),
    CONSTRAINT fk_prf_review_submissions_receipt FOREIGN KEY (
        tenant_id, command_receipt_id
    ) REFERENCES hris_performance.prf_command_receipts (
        tenant_id, command_receipt_id
    ),
    CONSTRAINT ck_prf_review_submissions_sequence CHECK (submission_no > 0),
    CONSTRAINT ck_prf_review_submissions_hashes CHECK (
        template_content_hash ~ '^[0-9a-f]{64}$'
        AND content_hash ~ '^[0-9a-f]{64}$'
    ),
    CONSTRAINT ck_prf_review_submissions_answers CHECK (
        jsonb_typeof(submitted_answers) = 'array'
        AND jsonb_array_length(submitted_answers) <= 500
    )
);

CREATE TABLE hris_performance.prf_review_command_results (
    review_command_result_internal_id BIGINT
        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    command_receipt_id UUID NOT NULL,
    review_id UUID NOT NULL,
    operation_id VARCHAR(80) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    result_payload JSONB NOT NULL,
    result_etag VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_prf_review_command_results_receipt
        UNIQUE (tenant_id, command_receipt_id),
    CONSTRAINT fk_prf_review_command_results_assignment FOREIGN KEY (
        tenant_id, review_id
    ) REFERENCES hris_performance.prf_review_assignments (
        tenant_id, review_id
    ),
    CONSTRAINT fk_prf_review_command_results_receipt FOREIGN KEY (
        tenant_id, command_receipt_id
    ) REFERENCES hris_performance.prf_command_receipts (
        tenant_id, command_receipt_id
    ),
    CONSTRAINT ck_prf_review_command_results_operation CHECK (
        operation_id IN ('saveReviewDraft', 'submitReview')
    ),
    CONSTRAINT ck_prf_review_command_results_hash CHECK (
        request_hash ~ '^[0-9a-f]{64}$'
    ),
    CONSTRAINT ck_prf_review_command_results_payload CHECK (
        jsonb_typeof(result_payload) = 'object'
    )
);

CREATE INDEX ix_prf_review_assignments_participant
    ON hris_performance.prf_review_assignments (
        tenant_id, participant_id, review_state, due_at, review_id
    );
CREATE INDEX ix_prf_review_assignments_reviewer
    ON hris_performance.prf_review_assignments (
        tenant_id, reviewer_principal_public_id, review_state, due_at, review_id
    );
CREATE INDEX ix_prf_review_submissions_review
    ON hris_performance.prf_review_submissions (
        tenant_id, review_id, submission_no
    );

CREATE FUNCTION hris_performance.prf_review_reject_immutable_mutation()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'PER_REVIEW_IMMUTABLE_EVIDENCE'
        USING ERRCODE = '55000';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_prf_review_submissions_immutable
    BEFORE UPDATE OR DELETE ON hris_performance.prf_review_submissions
    FOR EACH ROW EXECUTE FUNCTION
        hris_performance.prf_review_reject_immutable_mutation();
CREATE TRIGGER trg_prf_review_submissions_no_truncate
    BEFORE TRUNCATE ON hris_performance.prf_review_submissions
    FOR EACH STATEMENT EXECUTE FUNCTION
        hris_performance.prf_review_reject_immutable_mutation();
