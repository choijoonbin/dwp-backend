CREATE FUNCTION hris_performance.prf_per004_guard_preparation_update() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF ROW(NEW.tenant_id, NEW.configuration_id, NEW.artifact_public_id, NEW.artifact_revision,
           NEW.create_subject_principal_public_id, NEW.originating_action, NEW.create_idempotency_key,
           NEW.create_request_digest, NEW.schema_key, NEW.schema_version, NEW.payload_reference,
           NEW.payload_digest, NEW.scope_digest, NEW.preparation_receipt_id, NEW.created_at)
       IS DISTINCT FROM
       ROW(OLD.tenant_id, OLD.configuration_id, OLD.artifact_public_id, OLD.artifact_revision,
           OLD.create_subject_principal_public_id, OLD.originating_action, OLD.create_idempotency_key,
           OLD.create_request_digest, OLD.schema_key, OLD.schema_version, OLD.payload_reference,
           OLD.payload_digest, OLD.scope_digest, OLD.preparation_receipt_id, OLD.created_at)
       OR OLD.status <> 'PREPARED' OR NEW.status NOT IN ('FINALIZED', 'QUARANTINED') THEN
        RAISE EXCEPTION 'PER004_PREPARATION_IMMUTABLE_OR_ILLEGAL_TRANSITION' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

