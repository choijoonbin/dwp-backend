-- BASE-TFR-PER-004: extend the V17 artifact foundation without changing its history.
ALTER TABLE hris_performance.prf_per_artifact_versions
    ALTER COLUMN effective_from DROP NOT NULL,
    DROP CONSTRAINT ck_prf_per_artifact_versions_type_schema,
    DROP CONSTRAINT ck_prf_per_artifact_versions_owner,
    DROP CONSTRAINT ck_prf_per_artifact_versions_dates,
    ADD CONSTRAINT ck_prf_per_artifact_versions_type_schema CHECK (
        schema_version = 1 AND artifact_type IN (
            'COMPENSATION_GUIDELINES', 'COMPENSATION_POPULATION', 'COMPENSATION_PROPOSAL',
            'PERFORMANCE_REVIEW_FORM', 'PERFORMANCE_RATING_SCALE', 'PERFORMANCE_POLICY'
        )
    ),
    ADD CONSTRAINT ck_prf_per_artifact_versions_owner CHECK (
        (artifact_type IN ('COMPENSATION_GUIDELINES', 'COMPENSATION_POPULATION')
            AND owner_aggregate_type = 'COMPENSATION_CYCLE')
        OR (artifact_type = 'COMPENSATION_PROPOSAL'
            AND owner_aggregate_type = 'COMPENSATION_PROPOSAL_REVISION')
        OR (artifact_type IN (
                'PERFORMANCE_REVIEW_FORM', 'PERFORMANCE_RATING_SCALE', 'PERFORMANCE_POLICY'
            ) AND owner_aggregate_type = 'PERFORMANCE_CONFIGURATION_VERSION')
    ),
    ADD CONSTRAINT ck_prf_per_artifact_versions_dates CHECK (
        (artifact_type IN ('COMPENSATION_GUIDELINES', 'COMPENSATION_POPULATION', 'COMPENSATION_PROPOSAL')
            AND effective_from IS NOT NULL
            AND (effective_to IS NULL OR effective_to > effective_from))
        OR (artifact_type IN ('PERFORMANCE_REVIEW_FORM', 'PERFORMANCE_RATING_SCALE', 'PERFORMANCE_POLICY')
            AND effective_from IS NULL AND effective_to IS NULL)
    );

CREATE TABLE hris_performance.prf_per004_artifact_preparations (
    preparation_internal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    configuration_id UUID NOT NULL,
    artifact_public_id UUID NOT NULL,
    artifact_revision BIGINT NOT NULL,
    create_subject_principal_public_id UUID NOT NULL,
    originating_action VARCHAR(160) NOT NULL,
    create_idempotency_key VARCHAR(200) NOT NULL,
    create_request_digest CHAR(64) NOT NULL,
    schema_key VARCHAR(100) NOT NULL,
    schema_version INTEGER NOT NULL,
    payload_reference VARCHAR(80) NOT NULL,
    payload_digest CHAR(64) NOT NULL,
    scope_digest CHAR(64) NOT NULL,
    preparation_receipt_id UUID NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PREPARED',
    finalization_receipt_id UUID,
    platform_create_receipt_id UUID,
    platform_version BIGINT,
    quarantine_fence_id UUID,
    quarantine_evidence_digest CHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ,
    CONSTRAINT uk_prf_per004_preparations_artifact UNIQUE (tenant_id, artifact_public_id),
    CONSTRAINT uk_prf_per004_preparations_receipt UNIQUE (tenant_id, preparation_receipt_id),
    CONSTRAINT uk_prf_per004_preparations_create_identity UNIQUE (
        tenant_id, configuration_id, create_subject_principal_public_id,
        originating_action, create_idempotency_key
    ),
    CONSTRAINT fk_prf_per004_preparations_artifact FOREIGN KEY (tenant_id, artifact_public_id)
        REFERENCES hris_performance.prf_per_artifact_versions (tenant_id, public_id),
    CONSTRAINT ck_prf_per004_preparations_revision CHECK (artifact_revision > 0),
    CONSTRAINT ck_prf_per004_preparations_schema CHECK (
        schema_version = 1 AND schema_key IN (
            'dwp.hris.performance.review-form.v1',
            'dwp.hris.performance.rating-scale.v1',
            'dwp.hris.performance.policy.v1'
        )
    ),
    CONSTRAINT ck_prf_per004_preparations_reference CHECK (
        payload_reference = 'ref_per_artifact_' || artifact_public_id::text
    ),
    CONSTRAINT ck_prf_per004_preparations_digests CHECK (
        create_request_digest ~ '^[0-9a-f]{64}$'
        AND payload_digest ~ '^[0-9a-f]{64}$'
        AND scope_digest ~ '^[0-9a-f]{64}$'
        AND (quarantine_evidence_digest IS NULL OR quarantine_evidence_digest ~ '^[0-9a-f]{64}$')
    ),
    CONSTRAINT ck_prf_per004_preparations_status CHECK (
        (status = 'PREPARED' AND resolved_at IS NULL AND finalization_receipt_id IS NULL
            AND platform_create_receipt_id IS NULL AND platform_version IS NULL
            AND quarantine_fence_id IS NULL AND quarantine_evidence_digest IS NULL)
        OR (status = 'FINALIZED' AND resolved_at IS NOT NULL AND finalization_receipt_id IS NOT NULL
            AND platform_create_receipt_id IS NOT NULL AND platform_version > 0
            AND quarantine_fence_id IS NULL AND quarantine_evidence_digest IS NULL)
        OR (status = 'QUARANTINED' AND resolved_at IS NOT NULL AND finalization_receipt_id IS NULL
            AND platform_create_receipt_id IS NULL AND platform_version IS NULL
            AND quarantine_fence_id IS NOT NULL AND quarantine_evidence_digest IS NOT NULL)
    )
);

