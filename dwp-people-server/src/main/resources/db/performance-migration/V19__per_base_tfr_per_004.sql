        payload_digest ~ '^[0-9a-f]{64}$' AND scope_digest ~ '^[0-9a-f]{64}$'
        AND evidence_digest ~ '^[0-9a-f]{64}$'
        AND (sample_scope_digest IS NULL OR sample_scope_digest ~ '^[0-9a-f]{64}$')
        AND (impact_digest IS NULL OR impact_digest ~ '^[0-9a-f]{64}$')
    ),
    CONSTRAINT ck_prf_per004_evidence_lineage CHECK (
        (receipt_kind = 'VALIDATION' AND prior_validation_receipt_id IS NULL
            AND sample_scope_digest IS NULL AND impact_digest IS NULL)
        OR (receipt_kind = 'SIMULATION' AND prior_validation_receipt_id IS NOT NULL
            AND sample_scope_digest IS NOT NULL AND impact_digest IS NOT NULL)
    )
