-- BASE-TFR-PER-008 / PERFORMANCE V20
-- Closed owner storage for feedback requests, server-derived assignments,
-- encrypted responses and immutable release snapshots. No seed or backfill.

CREATE TABLE hris_performance.prf_feedback_requests (
    request_internal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    public_id UUID NOT NULL,
    aggregate_version BIGINT NOT NULL DEFAULT 1,
    cycle_version_id UUID NOT NULL,
    subject_worker_public_id UUID NOT NULL,
    subject_assignment_public_id UUID NOT NULL,
    workforce_projection_head_id UUID NOT NULL,
    workforce_local_revision BIGINT NOT NULL,
    workforce_owner_revision BIGINT NOT NULL,
    workforce_snapshot_as_of TIMESTAMPTZ NOT NULL,
    workforce_owner_page_digest CHAR(64) NOT NULL,
    workforce_content_hash CHAR(64) NOT NULL,
    template_artifact_public_id UUID NOT NULL,
    template_configuration_id UUID NOT NULL,
    template_platform_version BIGINT NOT NULL,
    template_schema_key VARCHAR(100) NOT NULL,
    template_payload_digest CHAR(64) NOT NULL,
    template_scope_digest CHAR(64) NOT NULL,
    template_content_hash CHAR(64) NOT NULL,
    request_title VARCHAR(240) NOT NULL,
    authorization_principal_public_id UUID NOT NULL,
    create_command_receipt_id UUID NOT NULL,
    open_command_receipt_id UUID,
    close_command_receipt_id UUID,
    aggregation_command_receipt_id UUID,
    release_command_receipt_id UUID,
    cancel_command_receipt_id UUID,
    request_state VARCHAR(24) NOT NULL DEFAULT 'DRAFT',
    anonymity_mode VARCHAR(32) NOT NULL,
    requested_minimum_release_count INTEGER NOT NULL,
    privacy_minimum_release_count INTEGER NOT NULL,
    effective_minimum_release_count INTEGER NOT NULL,
    privacy_policy_public_id UUID NOT NULL,
    threshold_policy_revision VARCHAR(128) NOT NULL,
    threshold_policy_digest CHAR(64) NOT NULL,
    audience_policy_public_id UUID NOT NULL,
    audience_policy_revision VARCHAR(128) NOT NULL,
    audience_policy_digest CHAR(64) NOT NULL,
    opens_at TIMESTAMPTZ NOT NULL,
    closes_at TIMESTAMPTZ NOT NULL,
    audience_scope_digest CHAR(64) NOT NULL,
    execution_binding_digest CHAR(64) NOT NULL,
    scope_decision_revision VARCHAR(128) NOT NULL,
    authorization_decision_revision VARCHAR(128) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by UUID NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    aggregated_at TIMESTAMPTZ,
    released_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    CONSTRAINT uk_prf_feedback_requests_tenant_public UNIQUE (tenant_id, public_id),
    CONSTRAINT uk_prf_feedback_requests_bound_revision UNIQUE (
        tenant_id, public_id, workforce_projection_head_id, workforce_local_revision
    ),
    CONSTRAINT uk_prf_feedback_requests_tenant_internal UNIQUE (tenant_id, request_internal_id),
    CONSTRAINT fk_prf_feedback_requests_cycle_version FOREIGN KEY (tenant_id, cycle_version_id)
        REFERENCES hris_performance.prf_cycle_versions (tenant_id, cycle_version_id),
    CONSTRAINT fk_prf_feedback_requests_workforce_revision FOREIGN KEY (
        tenant_id, workforce_projection_head_id, workforce_local_revision
    ) REFERENCES hris_performance.prf_workforce_projection_revisions (
        tenant_id, projection_head_id, local_revision
    ),
    CONSTRAINT fk_prf_feedback_requests_subject_member FOREIGN KEY (
        tenant_id, workforce_projection_head_id, workforce_local_revision,
        subject_worker_public_id, subject_assignment_public_id
    ) REFERENCES hris_performance.prf_workforce_projection_members (
        tenant_id, projection_head_id, local_revision,
        worker_public_id, assignment_public_id
    ),
    CONSTRAINT fk_prf_feedback_requests_template_artifact FOREIGN KEY (
        tenant_id, template_artifact_public_id
    ) REFERENCES hris_performance.prf_per_artifact_versions (tenant_id, public_id),
    CONSTRAINT fk_prf_feedback_requests_template_binding FOREIGN KEY (
        tenant_id, template_configuration_id, template_platform_version
    ) REFERENCES hris_performance.prf_per004_configuration_version_bindings (
        tenant_id, configuration_id, platform_version
    ),
    CONSTRAINT fk_prf_feedback_requests_create_receipt FOREIGN KEY (
        tenant_id, create_command_receipt_id
    ) REFERENCES hris_performance.prf_command_receipts (tenant_id, command_receipt_id),
    CONSTRAINT fk_prf_feedback_requests_open_receipt FOREIGN KEY (
        tenant_id, open_command_receipt_id
    ) REFERENCES hris_performance.prf_command_receipts (tenant_id, command_receipt_id),
    CONSTRAINT fk_prf_feedback_requests_close_receipt FOREIGN KEY (
        tenant_id, close_command_receipt_id
    ) REFERENCES hris_performance.prf_command_receipts (tenant_id, command_receipt_id),
    CONSTRAINT fk_prf_feedback_requests_aggregation_receipt FOREIGN KEY (
        tenant_id, aggregation_command_receipt_id
    ) REFERENCES hris_performance.prf_command_receipts (tenant_id, command_receipt_id),
    CONSTRAINT fk_prf_feedback_requests_release_receipt FOREIGN KEY (
        tenant_id, release_command_receipt_id
    ) REFERENCES hris_performance.prf_command_receipts (tenant_id, command_receipt_id),
    CONSTRAINT fk_prf_feedback_requests_cancel_receipt FOREIGN KEY (
        tenant_id, cancel_command_receipt_id
    ) REFERENCES hris_performance.prf_command_receipts (tenant_id, command_receipt_id),
    CONSTRAINT ck_prf_feedback_requests_version CHECK (aggregate_version > 0),
    CONSTRAINT ck_prf_feedback_requests_state CHECK (
        request_state IN ('DRAFT', 'OPEN', 'CLOSED', 'AGGREGATED', 'RELEASED', 'CANCELLED')
    ),
    CONSTRAINT ck_prf_feedback_requests_anonymity CHECK (
        anonymity_mode IN ('IDENTIFIED', 'MASKED', 'ANONYMOUS_AGGREGATE')
    ),
    CONSTRAINT ck_prf_feedback_requests_threshold CHECK (
        requested_minimum_release_count > 0
        AND privacy_minimum_release_count > 0
        AND effective_minimum_release_count = GREATEST(
            requested_minimum_release_count, privacy_minimum_release_count)
    ),
    CONSTRAINT ck_prf_feedback_requests_window CHECK (opens_at < closes_at),
    CONSTRAINT ck_prf_feedback_requests_template CHECK (
        template_platform_version > 0
        AND template_schema_key = 'dwp.hris.performance.review-form.v1'
        AND template_payload_digest ~ '^[0-9a-f]{64}$'
        AND template_scope_digest ~ '^[0-9a-f]{64}$'
        AND template_content_hash ~ '^[0-9a-f]{64}$'
        AND template_content_hash = template_payload_digest
        AND btrim(request_title) <> ''
    ),
    CONSTRAINT ck_prf_feedback_requests_digests CHECK (
        audience_scope_digest ~ '^[0-9a-f]{64}$'
        AND execution_binding_digest ~ '^[0-9a-f]{64}$'
    ),
    CONSTRAINT ck_prf_feedback_requests_revisions CHECK (
        workforce_local_revision > 0 AND workforce_owner_revision > 0
        AND workforce_owner_page_digest ~ '^[0-9a-f]{64}$'
        AND workforce_content_hash ~ '^[0-9a-f]{64}$'
        AND btrim(threshold_policy_revision) <> ''
        AND threshold_policy_digest ~ '^[0-9a-f]{64}$'
        AND btrim(audience_policy_revision) <> ''
        AND audience_policy_digest ~ '^[0-9a-f]{64}$'
        AND btrim(scope_decision_revision) <> ''
        AND btrim(authorization_decision_revision) <> ''
    ),
    CONSTRAINT ck_prf_feedback_requests_milestones CHECK (
        (request_state = 'AGGREGATED' AND aggregated_at IS NOT NULL
            AND released_at IS NULL AND cancelled_at IS NULL)
        OR (request_state = 'RELEASED' AND aggregated_at IS NOT NULL
            AND released_at IS NOT NULL AND cancelled_at IS NULL
            AND aggregated_at <= released_at)
        OR (request_state = 'CANCELLED' AND cancelled_at IS NOT NULL
            AND released_at IS NULL)
        OR (request_state IN ('DRAFT', 'OPEN', 'CLOSED')
            AND aggregated_at IS NULL AND released_at IS NULL AND cancelled_at IS NULL)
    ),
    CONSTRAINT ck_prf_feedback_requests_lifecycle_receipts CHECK (
        (request_state = 'DRAFT' AND open_command_receipt_id IS NULL
            AND close_command_receipt_id IS NULL AND aggregation_command_receipt_id IS NULL
            AND release_command_receipt_id IS NULL AND cancel_command_receipt_id IS NULL)
        OR (request_state = 'OPEN' AND open_command_receipt_id IS NOT NULL
            AND close_command_receipt_id IS NULL AND aggregation_command_receipt_id IS NULL
            AND release_command_receipt_id IS NULL AND cancel_command_receipt_id IS NULL)
        OR (request_state = 'CLOSED' AND open_command_receipt_id IS NOT NULL
            AND close_command_receipt_id IS NOT NULL AND aggregation_command_receipt_id IS NULL
            AND release_command_receipt_id IS NULL AND cancel_command_receipt_id IS NULL)
        OR (request_state = 'AGGREGATED' AND open_command_receipt_id IS NOT NULL
            AND close_command_receipt_id IS NOT NULL AND aggregation_command_receipt_id IS NOT NULL
            AND release_command_receipt_id IS NULL AND cancel_command_receipt_id IS NULL)
        OR (request_state = 'RELEASED' AND open_command_receipt_id IS NOT NULL
            AND close_command_receipt_id IS NOT NULL AND aggregation_command_receipt_id IS NOT NULL
            AND release_command_receipt_id IS NOT NULL AND cancel_command_receipt_id IS NULL)
        OR (request_state = 'CANCELLED' AND release_command_receipt_id IS NULL
            AND cancel_command_receipt_id IS NOT NULL
            AND (close_command_receipt_id IS NULL OR open_command_receipt_id IS NOT NULL)
            AND (aggregation_command_receipt_id IS NULL
                OR (open_command_receipt_id IS NOT NULL AND close_command_receipt_id IS NOT NULL)))
    )
);

