            AND declined_at IS NULL AND cancelled_at IS NULL)
        OR (assignment_state = 'DECLINED' AND submitted_at IS NULL
            AND declined_at IS NOT NULL AND cancelled_at IS NULL)
        OR (assignment_state = 'CANCELLED' AND submitted_at IS NULL
            AND declined_at IS NULL AND cancelled_at IS NOT NULL)
    )
);

