CREATE FUNCTION hris_performance.prf_per008_assert_create_commit(
        checked_tenant BIGINT, checked_request UUID) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    request_row hris_performance.prf_feedback_requests%ROWTYPE;
    receipt_count INTEGER;
    assignment_count INTEGER;
    exact_assignment_count INTEGER;
    distinct_provider_count INTEGER;
BEGIN
    SELECT * INTO request_row
      FROM hris_performance.prf_feedback_requests request
     WHERE request.tenant_id = checked_tenant
       AND request.public_id = checked_request;
    IF NOT FOUND OR request_row.request_state <> 'DRAFT'
       OR request_row.aggregate_version <> 1 THEN
        RAISE EXCEPTION 'PER008_CREATE_REQUEST_COMMIT_INVALID' USING ERRCODE = '23514';
    END IF;

    SELECT COUNT(*) INTO receipt_count
      FROM hris_performance.prf_command_receipts receipt
     WHERE receipt.tenant_id = checked_tenant
       AND receipt.command_receipt_id = request_row.create_command_receipt_id
       AND receipt.originating_action = 'PEP-PER-015'
       AND receipt.command_type = 'FEEDBACK_REQUEST_CREATE'
       AND receipt.aggregate_id = checked_request
       AND receipt.expected_aggregate_version = 0
       AND receipt.applied_aggregate_version = 1
       AND receipt.result_ref = checked_request
       AND receipt.subject_principal_public_id
           = request_row.authorization_principal_public_id
       AND receipt.population_scope_digest = request_row.execution_binding_digest
       AND receipt.purpose_code = 'PERFORMANCE_FEEDBACK'
       AND receipt.receipt_state = 'SUCCEEDED'
       AND receipt.completed_at = request_row.created_at;

    SELECT COUNT(*),
           COUNT(*) FILTER (
               WHERE assignment.workforce_projection_head_id
                         = request_row.workforce_projection_head_id
                 AND assignment.workforce_local_revision
                         = request_row.workforce_local_revision
                 AND assignment.assignment_state = 'ASSIGNED'
                 AND assignment.submitted_at IS NULL
                 AND assignment.declined_at IS NULL
                 AND assignment.cancelled_at IS NULL
                 AND assignment.created_at = request_row.created_at
                 AND assignment.updated_at = request_row.created_at),
           COUNT(DISTINCT (
               assignment.provider_worker_public_id,
               assignment.provider_assignment_public_id))
      INTO assignment_count, exact_assignment_count, distinct_provider_count
      FROM hris_performance.prf_feedback_assignments assignment
     WHERE assignment.tenant_id = checked_tenant
       AND assignment.feedback_request_public_id = checked_request;

    IF receipt_count <> 1
       OR assignment_count < request_row.effective_minimum_release_count
       OR exact_assignment_count <> assignment_count
       OR distinct_provider_count <> assignment_count THEN
        RAISE EXCEPTION 'PER008_CREATE_COMMIT_INCOMPLETE' USING ERRCODE = '23514';
    END IF;
END;
$$;

