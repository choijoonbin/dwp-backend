-- Resolve, rather than invent, the already provisioned Performance runtime principal.
-- A candidate must hold the same direct DML shape on all four reused V1 seams and must
-- be an unprivileged, non-bypass role. Zero or multiple candidates is deployment drift,
-- so migration fails closed instead of broadening access or guessing a role name.
DO $$
DECLARE
    runtime_role NAME;
    candidate_count INTEGER;
BEGIN
    WITH direct_dml AS (
        SELECT acl.grantee, relation.relname, acl.privilege_type
          FROM pg_class relation
          JOIN pg_namespace namespace ON namespace.oid = relation.relnamespace
          CROSS JOIN LATERAL aclexplode(
              COALESCE(relation.relacl, acldefault('r', relation.relowner))) acl
         WHERE namespace.nspname = 'hris_performance'
           AND relation.relname IN (
               'prf_cycles', 'prf_cycle_versions',
               'prf_command_receipts', 'prf_outbox_events'
           )
           AND relation.relkind IN ('r', 'p')
           AND acl.grantee <> 0
           AND acl.grantee <> relation.relowner
    ), common_dml AS (
        SELECT grantee
          FROM direct_dml
         GROUP BY grantee
        HAVING COUNT(DISTINCT relname) FILTER (WHERE privilege_type = 'SELECT') = 4
           AND COUNT(DISTINCT relname) FILTER (WHERE privilege_type = 'INSERT') = 4
           AND COUNT(DISTINCT relname) FILTER (WHERE privilege_type = 'UPDATE') = 4
           AND COUNT(DISTINCT relname) FILTER (WHERE privilege_type = 'DELETE') = 4
    ), safe_candidates AS (
        SELECT role.rolname
          FROM common_dml candidate
          JOIN pg_roles role ON role.oid = candidate.grantee
         WHERE NOT role.rolsuper
           AND NOT role.rolcreaterole
           AND NOT role.rolcreatedb
           AND NOT role.rolreplication
           AND NOT role.rolbypassrls
    )
    SELECT MIN(rolname), COUNT(*) INTO runtime_role, candidate_count
