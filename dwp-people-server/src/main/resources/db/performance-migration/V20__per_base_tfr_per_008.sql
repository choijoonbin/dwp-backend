CREATE FUNCTION hris_performance.prf_per008_validate_snapshot_insert() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    request_row hris_performance.prf_feedback_requests%ROWTYPE;
    actual_submitted_count INTEGER;
    actual_source_set_digest TEXT;
BEGIN
    SELECT * INTO request_row
      FROM hris_performance.prf_feedback_requests request
     WHERE request.tenant_id = NEW.tenant_id
       AND request.public_id = NEW.feedback_request_public_id
       AND request.request_state = 'CLOSED';
    IF NOT FOUND THEN
        RAISE EXCEPTION 'PER008_SNAPSHOT_BINDING_INVALID' USING ERRCODE = '23514';
    END IF;
    SELECT COUNT(DISTINCT assignment.public_id),
           pg_catalog.encode(pg_catalog.sha256(pg_catalog.convert_to(COALESCE(
               string_agg(
                   response.public_id::TEXT || ':'
                   || response.feedback_assignment_public_id::TEXT || ':'
                   || response.template_content_hash || ':'
                   || response.canonical_content_hmac || ':'
                   || response.digest_key_version_public_id::TEXT,
                   '|' ORDER BY response.public_id::TEXT), ''), 'UTF8')), 'hex')
      INTO actual_submitted_count, actual_source_set_digest
      FROM hris_performance.prf_feedback_assignments assignment
      JOIN hris_performance.prf_feedback_responses response
        ON response.tenant_id = assignment.tenant_id
       AND response.feedback_request_public_id = assignment.feedback_request_public_id
       AND response.feedback_assignment_public_id = assignment.public_id
     WHERE assignment.tenant_id = NEW.tenant_id
       AND assignment.feedback_request_public_id = NEW.feedback_request_public_id
       AND assignment.assignment_state = 'SUBMITTED';
    IF actual_submitted_count <> NEW.distinct_submitted_count
       OR actual_submitted_count < request_row.effective_minimum_release_count
       OR actual_source_set_digest <> NEW.source_set_digest
       OR NEW.aggregation_algorithm_version
            <> 'PerformanceFeedbackAggregate.v1/mean-text-v1'
       OR request_row.privacy_policy_public_id <> NEW.privacy_policy_public_id
       OR request_row.threshold_policy_revision <> NEW.threshold_policy_revision
       OR request_row.threshold_policy_digest <> NEW.threshold_policy_digest
       OR NOT EXISTS (
        SELECT 1 FROM hris_performance.prf_command_receipts receipt
         WHERE receipt.tenant_id = NEW.tenant_id
           AND receipt.command_receipt_id = NEW.aggregation_command_receipt_id
           AND receipt.originating_action = 'owner.people.performance-feedback.lifecycle.v1:aggregate'
           AND receipt.command_type = 'FEEDBACK_REQUEST_LIFECYCLE'
           AND receipt.aggregate_id = NEW.feedback_request_public_id
           AND receipt.expected_aggregate_version = request_row.aggregate_version
           AND receipt.applied_aggregate_version = request_row.aggregate_version + 1
           AND receipt.result_ref = NEW.feedback_request_public_id
           AND receipt.purpose_code = 'PERFORMANCE_FEEDBACK_LIFECYCLE'
           AND receipt.receipt_state = 'SUCCEEDED'
           AND receipt.completed_at = NEW.aggregated_at
       ) THEN
        RAISE EXCEPTION 'PER008_SNAPSHOT_BINDING_INVALID' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION hris_performance.prf_per008_assert_snapshot_commit(
        checked_tenant BIGINT, checked_request UUID) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    request_row hris_performance.prf_feedback_requests%ROWTYPE;
    snapshot_count INTEGER;
    exact_snapshot_count INTEGER;
BEGIN
    SELECT * INTO request_row
      FROM hris_performance.prf_feedback_requests request
     WHERE request.tenant_id = checked_tenant
       AND request.public_id = checked_request;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'PER008_SNAPSHOT_REQUEST_MISSING' USING ERRCODE = '23514';
    END IF;
    SELECT COUNT(*), COUNT(*) FILTER (
               WHERE snapshot.aggregation_command_receipt_id
                     = request_row.aggregation_command_receipt_id)
      INTO snapshot_count, exact_snapshot_count
      FROM hris_performance.prf_feedback_release_snapshots snapshot
     WHERE snapshot.tenant_id = checked_tenant
       AND snapshot.feedback_request_public_id = checked_request;

    IF request_row.request_state IN ('AGGREGATED', 'RELEASED') THEN
        IF request_row.aggregation_command_receipt_id IS NULL
           OR snapshot_count <> 1 OR exact_snapshot_count <> 1 THEN
            RAISE EXCEPTION 'PER008_REQUIRED_SNAPSHOT_COMMIT_INVALID' USING ERRCODE = '23514';
        END IF;
    ELSIF request_row.request_state = 'CANCELLED'
          AND request_row.aggregation_command_receipt_id IS NOT NULL THEN
        -- Cancellation after aggregation preserves the immutable collected evidence.
        IF snapshot_count <> 1 OR exact_snapshot_count <> 1 THEN
            RAISE EXCEPTION 'PER008_CANCELLED_SNAPSHOT_COMMIT_INVALID' USING ERRCODE = '23514';
        END IF;
    ELSIF snapshot_count <> 0 THEN
        RAISE EXCEPTION 'PER008_ORPHAN_SNAPSHOT_COMMIT_FORBIDDEN' USING ERRCODE = '23514';
    END IF;
END;
$$;

