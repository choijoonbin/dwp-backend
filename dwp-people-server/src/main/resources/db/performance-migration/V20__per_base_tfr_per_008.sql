CREATE FUNCTION hris_performance.prf_per008_guard_request_update() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    transition_receipt UUID;
    transition_action VARCHAR(160);
BEGIN
    IF ROW(NEW.tenant_id, NEW.public_id, NEW.cycle_version_id,
           NEW.subject_worker_public_id, NEW.subject_assignment_public_id,
           NEW.workforce_projection_head_id, NEW.workforce_local_revision,
           NEW.workforce_owner_revision, NEW.workforce_snapshot_as_of,
           NEW.workforce_owner_page_digest, NEW.workforce_content_hash,
