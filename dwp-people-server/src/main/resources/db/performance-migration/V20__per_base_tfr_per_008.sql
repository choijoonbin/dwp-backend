CREATE FUNCTION hris_performance.prf_per008_assert_submission_commit(
        checked_tenant BIGINT, checked_assignment UUID) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    assignment_row hris_performance.prf_feedback_assignments%ROWTYPE;
    response_count INTEGER;
    receipt_count INTEGER;
    event_count INTEGER;
    exact_chain_count INTEGER;
    cancellation_chain_count INTEGER;
BEGIN
    SELECT * INTO assignment_row
      FROM hris_performance.prf_feedback_assignments assignment
     WHERE assignment.tenant_id = checked_tenant
       AND assignment.public_id = checked_assignment;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'PER008_SUBMISSION_ASSIGNMENT_MISSING' USING ERRCODE = '23514';
    END IF;

    SELECT COUNT(*) INTO response_count
      FROM hris_performance.prf_feedback_responses response
     WHERE response.tenant_id = checked_tenant
       AND response.feedback_assignment_public_id = checked_assignment;
    SELECT COUNT(*) INTO receipt_count
      FROM hris_performance.prf_command_receipts receipt
     WHERE receipt.tenant_id = checked_tenant
       AND receipt.originating_action = 'PEP-PER-022'
       AND receipt.result_ref = checked_assignment;
    SELECT COUNT(*) INTO event_count
      FROM hris_performance.prf_outbox_events event
     WHERE event.tenant_id = checked_tenant
       AND event.event_type = 'PerformanceFeedbackSubmitted.v1'
       AND event.aggregate_id = checked_assignment;

    IF assignment_row.assignment_state = 'SUBMITTED' THEN
        SELECT COUNT(*) INTO exact_chain_count
          FROM hris_performance.prf_feedback_responses response
          JOIN hris_performance.prf_feedback_requests request
            ON request.tenant_id = response.tenant_id
           AND request.public_id = response.feedback_request_public_id
          JOIN hris_performance.prf_command_receipts receipt
            ON receipt.tenant_id = response.tenant_id
           AND receipt.command_receipt_id = response.submit_command_receipt_id
          JOIN hris_performance.prf_outbox_events event
            ON event.tenant_id = receipt.tenant_id
           AND event.command_receipt_id = receipt.command_receipt_id
         WHERE response.tenant_id = checked_tenant
           AND response.feedback_assignment_public_id = checked_assignment
           AND response.feedback_request_public_id = assignment_row.feedback_request_public_id
           AND response.submitted_at = assignment_row.submitted_at
           AND request.request_state = 'OPEN'
           AND response.submitted_at >= request.opens_at
           AND response.submitted_at < request.closes_at
           AND receipt.originating_action = 'PEP-PER-022'
           AND receipt.command_type = 'FEEDBACK_RESPONSE_SUBMIT'
           AND receipt.aggregate_id = assignment_row.feedback_request_public_id
           AND receipt.expected_aggregate_version = request.aggregate_version
           AND receipt.applied_aggregate_version = request.aggregate_version
           AND receipt.result_ref = checked_assignment
           AND receipt.subject_principal_public_id = assignment_row.provider_worker_public_id
           AND receipt.purpose_code = 'PERFORMANCE_FEEDBACK'
           AND receipt.receipt_state = 'SUCCEEDED'
           AND receipt.completed_at = response.submitted_at
           AND event.aggregate_type = 'PERFORMANCE_FEEDBACK_ASSIGNMENT'
           AND event.aggregate_id = checked_assignment
           AND event.aggregate_version = receipt.applied_aggregate_version
           AND event.event_type = 'PerformanceFeedbackSubmitted.v1'
           AND jsonb_typeof(event.payload) = 'object'
           AND (SELECT array_agg(payload_key.key ORDER BY payload_key.key)
                  FROM jsonb_object_keys(event.payload) AS payload_key(key))
               = ARRAY['feedbackAssignmentId', 'feedbackRequestId', 'submittedAt']::TEXT[]
           AND event.payload ->> 'feedbackAssignmentId' = checked_assignment::TEXT
           AND event.payload ->> 'feedbackRequestId'
               = assignment_row.feedback_request_public_id::TEXT
           AND (event.payload ->> 'submittedAt')::TIMESTAMPTZ = response.submitted_at;
        IF response_count <> 1 OR receipt_count <> 1 OR event_count <> 1
           OR exact_chain_count <> 1 THEN
            RAISE EXCEPTION 'PER008_SUBMISSION_COMMIT_INCOMPLETE' USING ERRCODE = '23514';
        END IF;
    ELSIF assignment_row.assignment_state = 'CANCELLED' THEN
        SELECT COUNT(*) INTO cancellation_chain_count
          FROM hris_performance.prf_feedback_requests request
          JOIN hris_performance.prf_command_receipts receipt
            ON receipt.tenant_id = request.tenant_id
           AND receipt.command_receipt_id = request.cancel_command_receipt_id
         WHERE request.tenant_id = checked_tenant
           AND request.public_id = assignment_row.feedback_request_public_id
           AND request.request_state = 'CANCELLED'
           AND request.cancelled_at = assignment_row.cancelled_at
           AND receipt.originating_action
               = 'owner.people.performance-feedback.lifecycle.v1:cancel'
           AND receipt.command_type = 'FEEDBACK_REQUEST_LIFECYCLE'
           AND receipt.aggregate_id = request.public_id
           AND receipt.expected_aggregate_version = request.aggregate_version - 1
           AND receipt.applied_aggregate_version = request.aggregate_version
           AND receipt.result_ref = request.public_id
           AND receipt.purpose_code = 'PERFORMANCE_FEEDBACK_LIFECYCLE'
           AND receipt.receipt_state = 'SUCCEEDED'
           AND receipt.completed_at = assignment_row.cancelled_at;
        IF response_count <> 0 OR receipt_count <> 0 OR event_count <> 0
           OR cancellation_chain_count <> 1 THEN
            RAISE EXCEPTION 'PER008_ASSIGNMENT_CANCELLATION_COMMIT_INVALID'
                USING ERRCODE = '23514';
        END IF;
    ELSIF response_count <> 0 OR receipt_count <> 0 OR event_count <> 0 THEN
        RAISE EXCEPTION 'PER008_NON_SUBMITTED_EFFECT_FORBIDDEN' USING ERRCODE = '23514';
    END IF;
END;
$$;

