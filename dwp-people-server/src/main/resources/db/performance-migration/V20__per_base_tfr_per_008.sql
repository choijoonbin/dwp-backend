BEGIN
    RAISE EXCEPTION 'PER008_APPEND_ONLY_EVIDENCE' USING ERRCODE = '23514';
END;
$$;

CREATE FUNCTION hris_performance.prf_per008_validate_request_insert() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.aggregate_version <> 1
       OR NEW.request_state <> 'DRAFT'
       OR NEW.open_command_receipt_id IS NOT NULL
       OR NEW.close_command_receipt_id IS NOT NULL
       OR NEW.aggregation_command_receipt_id IS NOT NULL
       OR NEW.release_command_receipt_id IS NOT NULL
       OR NEW.cancel_command_receipt_id IS NOT NULL
       OR NEW.aggregated_at IS NOT NULL
       OR NEW.released_at IS NOT NULL
       OR NEW.cancelled_at IS NOT NULL
       OR NOT EXISTS (
        SELECT 1
          FROM hris_performance.prf_per_artifact_versions artifact
          JOIN hris_performance.prf_per004_artifact_preparations preparation
            ON preparation.tenant_id = artifact.tenant_id
           AND preparation.artifact_public_id = artifact.public_id
          JOIN hris_performance.prf_per004_configuration_version_bindings binding
            ON binding.tenant_id = preparation.tenant_id
           AND binding.artifact_public_id = preparation.artifact_public_id
           AND binding.preparation_receipt_id = preparation.preparation_receipt_id
           AND binding.finalization_receipt_id = preparation.finalization_receipt_id
           AND binding.platform_create_receipt_id = preparation.platform_create_receipt_id
           AND binding.platform_version = preparation.platform_version
         WHERE artifact.tenant_id = NEW.tenant_id
           AND artifact.public_id = NEW.template_artifact_public_id
           AND artifact.artifact_type = 'PERFORMANCE_REVIEW_FORM'
           AND artifact.owner_aggregate_type = 'PERFORMANCE_CONFIGURATION_VERSION'
           AND artifact.schema_version = 1
           AND preparation.status = 'FINALIZED'
           AND preparation.schema_key = NEW.template_schema_key
           AND preparation.schema_version = 1
           AND binding.configuration_id = NEW.template_configuration_id
           AND binding.platform_version = NEW.template_platform_version
           AND binding.schema_key = NEW.template_schema_key
           AND binding.schema_version = 1
           AND artifact.canonical_content_digest = NEW.template_payload_digest
           AND preparation.payload_digest = NEW.template_payload_digest
           AND binding.payload_digest = NEW.template_payload_digest
           AND preparation.scope_digest = NEW.template_scope_digest
           AND binding.scope_digest = NEW.template_scope_digest
    ) OR NOT EXISTS (
        SELECT 1
          FROM hris_performance.prf_workforce_projection_revisions revision
         WHERE revision.tenant_id = NEW.tenant_id
           AND revision.projection_head_id = NEW.workforce_projection_head_id
           AND revision.local_revision = NEW.workforce_local_revision
           AND revision.owner_revision = NEW.workforce_owner_revision
           AND revision.snapshot_as_of = NEW.workforce_snapshot_as_of
           AND revision.owner_page_digest = NEW.workforce_owner_page_digest
           AND revision.content_hash = NEW.workforce_content_hash
    ) OR NOT EXISTS (
        SELECT 1
          FROM hris_performance.prf_command_receipts receipt
         WHERE receipt.tenant_id = NEW.tenant_id
           AND receipt.command_receipt_id = NEW.create_command_receipt_id
           AND receipt.originating_action = 'PEP-PER-015'
           AND receipt.command_type = 'FEEDBACK_REQUEST_CREATE'
           AND receipt.aggregate_id = NEW.public_id
           AND receipt.expected_aggregate_version = 0
           AND receipt.applied_aggregate_version IS NULL
           AND receipt.result_ref IS NULL
           AND receipt.subject_principal_public_id = NEW.authorization_principal_public_id
           AND receipt.purpose_code = 'PERFORMANCE_FEEDBACK'
           AND receipt.population_scope_digest = NEW.execution_binding_digest
           AND receipt.receipt_state = 'ACCEPTED'
           AND receipt.completed_at IS NULL
    ) THEN
        RAISE EXCEPTION 'PER008_FROZEN_AUTHORITY_INVALID' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION hris_performance.prf_per008_validate_response_insert() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
          FROM hris_performance.prf_feedback_assignments assignment
          JOIN hris_performance.prf_feedback_requests request
            ON request.tenant_id = assignment.tenant_id
           AND request.public_id = assignment.feedback_request_public_id
         WHERE assignment.tenant_id = NEW.tenant_id
           AND assignment.public_id = NEW.feedback_assignment_public_id
           AND request.public_id = NEW.feedback_request_public_id
           AND request.template_content_hash = NEW.template_content_hash
           AND request.request_state = 'OPEN'
           AND NEW.submitted_at >= request.opens_at
           AND NEW.submitted_at < request.closes_at
           AND assignment.assignment_state = 'ASSIGNED'
           AND EXISTS (
               SELECT 1 FROM hris_performance.prf_command_receipts receipt
         WHERE receipt.tenant_id = NEW.tenant_id
           AND receipt.command_receipt_id = NEW.submit_command_receipt_id
           AND receipt.originating_action = 'PEP-PER-022'
                 AND receipt.command_type = 'FEEDBACK_RESPONSE_SUBMIT'
                 AND receipt.aggregate_id = request.public_id
                 AND receipt.expected_aggregate_version = request.aggregate_version
                 AND receipt.applied_aggregate_version = request.aggregate_version
                 AND receipt.result_ref = assignment.public_id
                 AND receipt.subject_principal_public_id = assignment.provider_worker_public_id
                 AND receipt.purpose_code = 'PERFORMANCE_FEEDBACK'
                 AND receipt.receipt_state = 'SUCCEEDED'
                 AND receipt.completed_at = NEW.submitted_at
           )
    ) THEN
        RAISE EXCEPTION 'PER008_RESPONSE_BINDING_INVALID' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION hris_performance.prf_per008_validate_assignment_insert() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.assignment_state <> 'ASSIGNED'
       OR NEW.submitted_at IS NOT NULL
       OR NEW.declined_at IS NOT NULL
       OR NEW.cancelled_at IS NOT NULL
       OR NOT EXISTS (
        SELECT 1
          FROM hris_performance.prf_feedback_requests request
          JOIN hris_performance.prf_command_receipts receipt
            ON receipt.tenant_id = request.tenant_id
