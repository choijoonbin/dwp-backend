           NEW.template_payload_digest, NEW.template_scope_digest,
           NEW.template_content_hash, NEW.request_title,
           NEW.authorization_principal_public_id, NEW.anonymity_mode,
           NEW.requested_minimum_release_count, NEW.privacy_minimum_release_count,
           NEW.effective_minimum_release_count, NEW.privacy_policy_public_id,
           NEW.threshold_policy_revision, NEW.threshold_policy_digest,
           NEW.audience_policy_public_id, NEW.audience_policy_revision,
           NEW.audience_policy_digest,
           NEW.opens_at, NEW.closes_at, NEW.audience_scope_digest,
           NEW.execution_binding_digest, NEW.scope_decision_revision,
           NEW.authorization_decision_revision, NEW.created_at, NEW.created_by)
       IS DISTINCT FROM
       ROW(OLD.tenant_id, OLD.public_id, OLD.cycle_version_id,
           OLD.subject_worker_public_id, OLD.subject_assignment_public_id,
           OLD.workforce_projection_head_id, OLD.workforce_local_revision,
           OLD.workforce_owner_revision, OLD.workforce_snapshot_as_of,
           OLD.workforce_owner_page_digest, OLD.workforce_content_hash,
           OLD.template_artifact_public_id, OLD.template_configuration_id,
           OLD.template_platform_version, OLD.template_schema_key,
           OLD.template_payload_digest, OLD.template_scope_digest,
           OLD.template_content_hash, OLD.request_title,
           OLD.authorization_principal_public_id, OLD.anonymity_mode,
           OLD.requested_minimum_release_count, OLD.privacy_minimum_release_count,
           OLD.effective_minimum_release_count, OLD.privacy_policy_public_id,
           OLD.threshold_policy_revision, OLD.threshold_policy_digest,
           OLD.audience_policy_public_id, OLD.audience_policy_revision,
           OLD.audience_policy_digest,
           OLD.opens_at, OLD.closes_at, OLD.audience_scope_digest,
           OLD.execution_binding_digest, OLD.scope_decision_revision,
           OLD.authorization_decision_revision, OLD.created_at, OLD.created_by)
       OR NEW.aggregate_version <> OLD.aggregate_version + 1
       OR NOT (
           (OLD.request_state = 'DRAFT' AND NEW.request_state IN ('OPEN', 'CANCELLED'))
           OR (OLD.request_state = 'OPEN' AND NEW.request_state IN ('CLOSED', 'CANCELLED'))
           OR (OLD.request_state = 'CLOSED' AND NEW.request_state IN ('AGGREGATED', 'CANCELLED'))
           OR (OLD.request_state = 'AGGREGATED' AND NEW.request_state IN ('RELEASED', 'CANCELLED'))
       ) THEN
        RAISE EXCEPTION 'PER008_REQUEST_IMMUTABLE_OR_ILLEGAL_TRANSITION' USING ERRCODE = '23514';
    END IF;
    IF NEW.create_command_receipt_id <> OLD.create_command_receipt_id THEN
        RAISE EXCEPTION 'PER008_CREATE_RECEIPT_IMMUTABLE' USING ERRCODE = '23514';
    END IF;
    transition_receipt := CASE NEW.request_state
        WHEN 'OPEN' THEN NEW.open_command_receipt_id
        WHEN 'CLOSED' THEN NEW.close_command_receipt_id
        WHEN 'AGGREGATED' THEN NEW.aggregation_command_receipt_id
        WHEN 'RELEASED' THEN NEW.release_command_receipt_id
        WHEN 'CANCELLED' THEN NEW.cancel_command_receipt_id
    END;
    transition_action := 'owner.people.performance-feedback.lifecycle.v1:' || CASE NEW.request_state
        WHEN 'OPEN' THEN 'open'
        WHEN 'CLOSED' THEN 'close'
        WHEN 'AGGREGATED' THEN 'aggregate'
        WHEN 'RELEASED' THEN 'release'
        WHEN 'CANCELLED' THEN 'cancel'
    END;
    IF transition_receipt IS NULL
       OR (NEW.request_state <> 'OPEN'
           AND NEW.open_command_receipt_id IS DISTINCT FROM OLD.open_command_receipt_id)
       OR (NEW.request_state <> 'CLOSED'
           AND NEW.close_command_receipt_id IS DISTINCT FROM OLD.close_command_receipt_id)
       OR (NEW.request_state <> 'AGGREGATED'
           AND NEW.aggregation_command_receipt_id IS DISTINCT FROM OLD.aggregation_command_receipt_id)
       OR (NEW.request_state <> 'RELEASED'
           AND NEW.release_command_receipt_id IS DISTINCT FROM OLD.release_command_receipt_id)
       OR (NEW.request_state <> 'CANCELLED'
           AND NEW.cancel_command_receipt_id IS DISTINCT FROM OLD.cancel_command_receipt_id)
       OR NOT EXISTS (
           SELECT 1 FROM hris_performance.prf_command_receipts receipt
            WHERE receipt.tenant_id = NEW.tenant_id
              AND receipt.command_receipt_id = transition_receipt
              AND receipt.originating_action = transition_action
              AND receipt.command_type = 'FEEDBACK_REQUEST_LIFECYCLE'
              AND receipt.aggregate_id = NEW.public_id
              AND receipt.expected_aggregate_version = OLD.aggregate_version
              AND receipt.applied_aggregate_version = NEW.aggregate_version
              AND receipt.result_ref = NEW.public_id
              AND receipt.purpose_code = 'PERFORMANCE_FEEDBACK_LIFECYCLE'
              AND receipt.receipt_state = 'SUCCEEDED'
              AND receipt.completed_at = NEW.updated_at
       ) THEN
        RAISE EXCEPTION 'PER008_LIFECYCLE_RECEIPT_INVALID' USING ERRCODE = '23514';
    END IF;
    IF NEW.request_state = 'CANCELLED' AND EXISTS (
        SELECT 1 FROM hris_performance.prf_feedback_assignments assignment
         WHERE assignment.tenant_id = NEW.tenant_id
           AND assignment.feedback_request_public_id = NEW.public_id
           AND assignment.assignment_state = 'ASSIGNED'
    ) THEN
        RAISE EXCEPTION 'PER008_OUTSTANDING_ASSIGNMENT_CANCELLATION_REQUIRED'
            USING ERRCODE = '23514';
    END IF;
    IF NEW.request_state IN ('AGGREGATED', 'RELEASED') AND NOT EXISTS (
        SELECT 1 FROM hris_performance.prf_feedback_release_snapshots snapshot
         WHERE snapshot.tenant_id = NEW.tenant_id
           AND snapshot.feedback_request_public_id = NEW.public_id
    ) THEN
        RAISE EXCEPTION 'PER008_RELEASE_SNAPSHOT_REQUIRED' USING ERRCODE = '23514';
    END IF;
    IF NEW.request_state = 'AGGREGATED' AND NOT EXISTS (
        SELECT 1 FROM hris_performance.prf_feedback_release_snapshots snapshot
         WHERE snapshot.tenant_id = NEW.tenant_id
           AND snapshot.feedback_request_public_id = NEW.public_id
           AND snapshot.aggregation_command_receipt_id = transition_receipt
    ) THEN
        RAISE EXCEPTION 'PER008_AGGREGATION_RECEIPT_MISMATCH' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION hris_performance.prf_per008_guard_assignment_update() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF ROW(NEW.tenant_id, NEW.public_id, NEW.feedback_request_public_id,
           NEW.provider_worker_public_id, NEW.provider_assignment_public_id,
           NEW.workforce_projection_head_id, NEW.workforce_local_revision,
           NEW.relationship_type, NEW.request_scoped_mask_label, NEW.created_at)
       IS DISTINCT FROM
       ROW(OLD.tenant_id, OLD.public_id, OLD.feedback_request_public_id,
           OLD.provider_worker_public_id, OLD.provider_assignment_public_id,
           OLD.workforce_projection_head_id, OLD.workforce_local_revision,
           OLD.relationship_type, OLD.request_scoped_mask_label, OLD.created_at)
       OR OLD.assignment_state <> 'ASSIGNED'
       OR NEW.assignment_state NOT IN ('SUBMITTED', 'CANCELLED')
       OR (NEW.assignment_state = 'SUBMITTED'
           AND NEW.updated_at IS DISTINCT FROM NEW.submitted_at)
       OR (NEW.assignment_state = 'CANCELLED'
           AND NEW.updated_at IS DISTINCT FROM NEW.cancelled_at)
       OR (NEW.assignment_state = 'CANCELLED' AND NOT EXISTS (
           SELECT 1
             FROM hris_performance.prf_feedback_requests request
             JOIN hris_performance.prf_command_receipts receipt
               ON receipt.tenant_id = request.tenant_id
              AND receipt.originating_action
                  = 'owner.people.performance-feedback.lifecycle.v1:cancel'
              AND receipt.command_type = 'FEEDBACK_REQUEST_LIFECYCLE'
              AND receipt.aggregate_id = request.public_id
              AND receipt.expected_aggregate_version = request.aggregate_version
              AND receipt.applied_aggregate_version = request.aggregate_version + 1
              AND receipt.result_ref = request.public_id
              AND receipt.purpose_code = 'PERFORMANCE_FEEDBACK_LIFECYCLE'
              AND receipt.receipt_state = 'SUCCEEDED'
              AND receipt.completed_at = NEW.cancelled_at
            WHERE request.tenant_id = NEW.tenant_id
              AND request.public_id = NEW.feedback_request_public_id
              AND request.request_state IN ('DRAFT', 'OPEN', 'CLOSED', 'AGGREGATED')
       )) THEN
        RAISE EXCEPTION 'PER008_ASSIGNMENT_IMMUTABLE_OR_ILLEGAL_TRANSITION' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION hris_performance.prf_per008_guard_receipt_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    old_is_per008 BOOLEAN;
    new_is_per008 BOOLEAN;
BEGIN
    old_is_per008 := OLD.originating_action IN (
        'PEP-PER-015',
        'PEP-PER-022',
        'owner.people.performance-feedback.lifecycle.v1:open',
        'owner.people.performance-feedback.lifecycle.v1:close',
        'owner.people.performance-feedback.lifecycle.v1:aggregate',
        'owner.people.performance-feedback.lifecycle.v1:release',
        'owner.people.performance-feedback.lifecycle.v1:cancel'
    );
    IF TG_OP = 'DELETE' THEN
        IF old_is_per008 THEN
            RAISE EXCEPTION 'PER008_RECEIPT_EVIDENCE_IMMUTABLE' USING ERRCODE = '23514';
        END IF;
        RETURN OLD;
    END IF;

    new_is_per008 := NEW.originating_action IN (
        'PEP-PER-015',
        'PEP-PER-022',
        'owner.people.performance-feedback.lifecycle.v1:open',
        'owner.people.performance-feedback.lifecycle.v1:close',
        'owner.people.performance-feedback.lifecycle.v1:aggregate',
        'owner.people.performance-feedback.lifecycle.v1:release',
        'owner.people.performance-feedback.lifecycle.v1:cancel'
    );
    IF old_is_per008 IS DISTINCT FROM new_is_per008 THEN
        RAISE EXCEPTION 'PER008_RECEIPT_ACTION_MUTATION_FORBIDDEN' USING ERRCODE = '23514';
    END IF;
    IF NOT old_is_per008 THEN
        RETURN NEW;
    END IF;
    IF ROW(NEW.internal_id, NEW.command_receipt_id, NEW.tenant_id,
           NEW.idempotency_key, NEW.command_type, NEW.originating_action,
           NEW.actor_id, NEW.subject_principal_public_id, NEW.aggregate_id,
           NEW.expected_aggregate_version, NEW.request_hash,
           NEW.field_policy_revision, NEW.purpose_code,
           NEW.authorization_revision, NEW.error_code, NEW.accepted_at)
       IS DISTINCT FROM
       ROW(OLD.internal_id, OLD.command_receipt_id, OLD.tenant_id,
           OLD.idempotency_key, OLD.command_type, OLD.originating_action,
           OLD.actor_id, OLD.subject_principal_public_id, OLD.aggregate_id,
           OLD.expected_aggregate_version, OLD.request_hash,
           OLD.field_policy_revision, OLD.purpose_code,
           OLD.authorization_revision, OLD.error_code, OLD.accepted_at) THEN
        RAISE EXCEPTION 'PER008_RECEIPT_IDENTITY_OR_INTENT_IMMUTABLE'
            USING ERRCODE = '23514';
    END IF;

    IF OLD.originating_action = 'PEP-PER-015'
       AND OLD.receipt_state = 'ACCEPTED'
       AND NEW.receipt_state = 'ACCEPTED'
       AND OLD.applied_aggregate_version IS NULL
       AND NEW.applied_aggregate_version IS NULL
       AND OLD.result_ref IS NULL AND NEW.result_ref IS NULL
       AND OLD.completed_at IS NULL AND NEW.completed_at IS NULL
       AND NEW.population_scope_digest IS DISTINCT FROM OLD.population_scope_digest
       AND NOT EXISTS (
           SELECT 1 FROM hris_performance.prf_feedback_requests request
            WHERE request.tenant_id = OLD.tenant_id
              AND request.create_command_receipt_id = OLD.command_receipt_id
       ) THEN
        RETURN NEW;
    END IF;

    IF OLD.originating_action = 'PEP-PER-015'
       AND OLD.receipt_state = 'ACCEPTED'
       AND NEW.receipt_state = 'SUCCEEDED'
       AND OLD.applied_aggregate_version IS NULL
       AND NEW.applied_aggregate_version = 1
       AND OLD.result_ref IS NULL
       AND NEW.result_ref = NEW.aggregate_id
       AND OLD.completed_at IS NULL
       AND NEW.completed_at IS NOT NULL
       AND NEW.population_scope_digest = OLD.population_scope_digest
       AND EXISTS (
           SELECT 1
             FROM hris_performance.prf_feedback_requests request
            WHERE request.tenant_id = NEW.tenant_id
              AND request.public_id = NEW.aggregate_id
              AND request.create_command_receipt_id = NEW.command_receipt_id
              AND request.request_state = 'DRAFT'
              AND request.aggregate_version = 1
              AND request.authorization_principal_public_id
                  = NEW.subject_principal_public_id
              AND request.execution_binding_digest = NEW.population_scope_digest
              AND (SELECT COUNT(*)
                     FROM hris_performance.prf_feedback_assignments assignment
                    WHERE assignment.tenant_id = request.tenant_id
                      AND assignment.feedback_request_public_id = request.public_id)
                  >= request.effective_minimum_release_count
       ) THEN
        RETURN NEW;
    END IF;

    RAISE EXCEPTION 'PER008_RECEIPT_MUTATION_FORBIDDEN' USING ERRCODE = '23514';
END;
$$;

