-- MIGLEASE-HRIS-W1-PER-001 / BASE-TFR-PER-005
-- Evaluation-cycle draft/version/publish and minimum-field participant preview only.

CREATE TABLE hris_performance.prf_cycles (
    internal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id UUID NOT NULL,
    tenant_id BIGINT NOT NULL,
    cycle_key VARCHAR(100) NOT NULL,
    display_name VARCHAR(240) NOT NULL,
    lifecycle_state VARCHAR(24) NOT NULL,
    active_version_no INTEGER,
    aggregate_version BIGINT NOT NULL DEFAULT 0,
    retention_policy_id UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT NOT NULL,
    CONSTRAINT uk_prf_cycles_tenant_id UNIQUE (tenant_id, cycle_id),
    CONSTRAINT uk_prf_cycles_tenant_key UNIQUE (tenant_id, cycle_key),
    CONSTRAINT ck_prf_cycles_key_nonblank CHECK (btrim(cycle_key) <> ''),
    CONSTRAINT ck_prf_cycles_name_nonblank CHECK (btrim(display_name) <> ''),
    CONSTRAINT ck_prf_cycles_state CHECK (
        lifecycle_state IN ('DRAFT', 'VALIDATED', 'PUBLISHED', 'RETIRED')
    ),
    CONSTRAINT ck_prf_cycles_version CHECK (
        aggregate_version >= 0 AND (active_version_no IS NULL OR active_version_no > 0)
    )
);

CREATE TABLE hris_performance.prf_cycle_versions (
    internal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_version_id UUID NOT NULL,
    tenant_id BIGINT NOT NULL,
    cycle_id UUID NOT NULL,
    version_no INTEGER NOT NULL,
    version_state VARCHAR(20) NOT NULL,
    aggregate_version BIGINT NOT NULL DEFAULT 0,
    effective_from TIMESTAMPTZ NOT NULL,
    effective_to TIMESTAMPTZ,
    timezone_id VARCHAR(80) NOT NULL,
    policy_version_id UUID NOT NULL,
    population_rule_version_id UUID,
    content_hash CHAR(64) NOT NULL,
    publication_approval_ref UUID,
    authored_by BIGINT NOT NULL,
    published_at TIMESTAMPTZ,
    published_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_prf_cycle_versions_tenant_id UNIQUE (tenant_id, cycle_version_id),
    CONSTRAINT uk_prf_cycle_versions_tenant_no UNIQUE (tenant_id, cycle_id, version_no),
    CONSTRAINT fk_prf_cycle_versions_cycle FOREIGN KEY (tenant_id, cycle_id)
        REFERENCES hris_performance.prf_cycles (tenant_id, cycle_id),
    CONSTRAINT ck_prf_cycle_versions_number CHECK (version_no > 0),
    CONSTRAINT ck_prf_cycle_versions_aggregate_version CHECK (aggregate_version >= 0),
    CONSTRAINT ck_prf_cycle_versions_state CHECK (
        version_state IN ('DRAFT', 'VALIDATED', 'PUBLISHED', 'SUPERSEDED')
    ),
    CONSTRAINT ck_prf_cycle_versions_period CHECK (
        effective_to IS NULL OR effective_from < effective_to
    ),
    CONSTRAINT ck_prf_cycle_versions_timezone CHECK (btrim(timezone_id) <> ''),
    CONSTRAINT ck_prf_cycle_versions_hash CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_prf_cycle_versions_publication CHECK (
        (version_state IN ('PUBLISHED', 'SUPERSEDED')
            AND publication_approval_ref IS NOT NULL
            AND published_at IS NOT NULL
            AND published_by IS NOT NULL)
        OR
        (version_state NOT IN ('PUBLISHED', 'SUPERSEDED')
            AND publication_approval_ref IS NULL
            AND published_at IS NULL
            AND published_by IS NULL)
    ),
    CONSTRAINT ck_prf_cycle_versions_author_publisher_sod CHECK (
        published_by IS NULL OR published_by <> authored_by
    )
);

CREATE UNIQUE INDEX ux_prf_cycle_versions_working
    ON hris_performance.prf_cycle_versions (tenant_id, cycle_id)
    WHERE version_state IN ('DRAFT', 'VALIDATED');

CREATE UNIQUE INDEX ux_prf_cycle_versions_published
    ON hris_performance.prf_cycle_versions (tenant_id, cycle_id)
    WHERE version_state = 'PUBLISHED';

CREATE TABLE hris_performance.prf_cycle_stages (
    internal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id UUID NOT NULL,
    tenant_id BIGINT NOT NULL,
    cycle_version_id UUID NOT NULL,
    stage_key VARCHAR(80) NOT NULL,
    stage_type VARCHAR(32) NOT NULL,
    sequence_no INTEGER NOT NULL,
    opens_at TIMESTAMPTZ NOT NULL,
    closes_at TIMESTAMPTZ NOT NULL,
    required BOOLEAN NOT NULL DEFAULT TRUE,
    stage_config JSONB NOT NULL DEFAULT '{}'::JSONB,
    CONSTRAINT uk_prf_cycle_stages_tenant_id UNIQUE (tenant_id, stage_id),
    CONSTRAINT uk_prf_cycle_stages_tenant_key UNIQUE (
        tenant_id, cycle_version_id, stage_key
    ),
    CONSTRAINT uk_prf_cycle_stages_tenant_sequence UNIQUE (
        tenant_id, cycle_version_id, sequence_no
    ),
    CONSTRAINT fk_prf_cycle_stages_version FOREIGN KEY (tenant_id, cycle_version_id)
        REFERENCES hris_performance.prf_cycle_versions (tenant_id, cycle_version_id),
    CONSTRAINT ck_prf_cycle_stages_key_nonblank CHECK (btrim(stage_key) <> ''),
    CONSTRAINT ck_prf_cycle_stages_type_nonblank CHECK (btrim(stage_type) <> ''),
    CONSTRAINT ck_prf_cycle_stages_sequence CHECK (sequence_no > 0),
    CONSTRAINT ck_prf_cycle_stages_period CHECK (opens_at < closes_at),
    CONSTRAINT ck_prf_cycle_stages_config_object CHECK (
        jsonb_typeof(stage_config) = 'object'
    )
);

CREATE TABLE hris_performance.prf_population_previews (
    internal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    population_preview_id UUID NOT NULL,
    tenant_id BIGINT NOT NULL,
    cycle_version_id UUID NOT NULL,
    source_cycle_aggregate_version BIGINT NOT NULL,
    population_rule_version_id UUID NOT NULL,
    workforce_snapshot_id UUID NOT NULL,
    workforce_snapshot_revision BIGINT NOT NULL,
    preview_state VARCHAR(24) NOT NULL,
    participant_count INTEGER NOT NULL,
    reviewer_assignment_count INTEGER NOT NULL,
    content_hash CHAR(64) NOT NULL,
    aggregate_version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL,
    expires_at TIMESTAMPTZ,
    CONSTRAINT uk_prf_population_previews_tenant_id UNIQUE (
        tenant_id, population_preview_id
    ),
    CONSTRAINT fk_prf_population_previews_version FOREIGN KEY (tenant_id, cycle_version_id)
        REFERENCES hris_performance.prf_cycle_versions (tenant_id, cycle_version_id),
    CONSTRAINT ck_prf_population_previews_revision CHECK (
        source_cycle_aggregate_version >= 0
        AND workforce_snapshot_revision > 0
        AND aggregate_version >= 0
    ),
    CONSTRAINT ck_prf_population_previews_state CHECK (
        preview_state IN ('READY', 'STALE', 'RESULT_UNKNOWN')
    ),
    CONSTRAINT ck_prf_population_previews_counts CHECK (
        participant_count >= 0 AND reviewer_assignment_count >= 0
    ),
    CONSTRAINT ck_prf_population_previews_hash CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_prf_population_previews_expiry CHECK (
        expires_at IS NULL OR created_at < expires_at
    )
);

CREATE UNIQUE INDEX ux_prf_population_previews_ready_snapshot
    ON hris_performance.prf_population_previews (
        tenant_id, cycle_version_id, population_rule_version_id,
        source_cycle_aggregate_version, workforce_snapshot_id,
        workforce_snapshot_revision
    )
    WHERE preview_state = 'READY';

CREATE TABLE hris_performance.prf_population_preview_members (
    internal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    population_preview_id UUID NOT NULL,
    participant_ref UUID NOT NULL,
    primary_assignment_ref UUID NOT NULL,
    workforce_status VARCHAR(24) NOT NULL,
    organization_ref UUID NOT NULL,
    reviewer_assignment_ref UUID,
    job_profile_ref UUID,
    grade_ref UUID,
    eligibility_code VARCHAR(40) NOT NULL,
    CONSTRAINT uk_prf_population_preview_members_participant UNIQUE (
        tenant_id, population_preview_id, participant_ref, primary_assignment_ref
    ),
    CONSTRAINT fk_prf_population_preview_members_preview FOREIGN KEY (
        tenant_id, population_preview_id
    ) REFERENCES hris_performance.prf_population_previews (
        tenant_id, population_preview_id
    ),
    CONSTRAINT ck_prf_population_preview_members_status CHECK (
        workforce_status IN ('PENDING', 'ACTIVE', 'INACTIVE', 'TERMINATED')
    ),
    CONSTRAINT ck_prf_population_preview_members_eligibility CHECK (
        eligibility_code IN ('INCLUDED', 'EXCLUDED', 'REVIEW_REQUIRED')
    )
);

CREATE TABLE hris_performance.prf_command_receipts (
    internal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    command_receipt_id UUID NOT NULL,
    tenant_id BIGINT NOT NULL,
    idempotency_key VARCHAR(200) NOT NULL,
    command_type VARCHAR(80) NOT NULL,
    originating_action VARCHAR(160) NOT NULL,
    actor_id BIGINT NOT NULL,
    subject_principal_public_id UUID NOT NULL,
    aggregate_id UUID NOT NULL,
    expected_aggregate_version BIGINT NOT NULL,
    applied_aggregate_version BIGINT,
    request_hash CHAR(64) NOT NULL,
    population_scope_digest CHAR(64) NOT NULL,
    field_policy_revision BIGINT NOT NULL,
    purpose_code VARCHAR(80) NOT NULL,
    authorization_revision BIGINT NOT NULL,
    receipt_state VARCHAR(24) NOT NULL,
    result_ref UUID,
    error_code VARCHAR(100),
    accepted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    CONSTRAINT uk_prf_command_receipts_tenant_id UNIQUE (
        tenant_id, command_receipt_id
    ),
    CONSTRAINT uk_prf_command_receipts_idempotency UNIQUE (
        tenant_id, subject_principal_public_id, originating_action, idempotency_key
    ),
    CONSTRAINT ck_prf_command_receipts_expected_version CHECK (
        expected_aggregate_version >= 0
    ),
    CONSTRAINT ck_prf_command_receipts_applied_version CHECK (
        applied_aggregate_version IS NULL OR applied_aggregate_version >= 0
    ),
    CONSTRAINT ck_prf_command_receipts_request_hash CHECK (request_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_prf_command_receipts_scope_hash CHECK (
        population_scope_digest ~ '^[0-9a-f]{64}$'
    ),
    CONSTRAINT ck_prf_command_receipts_revisions CHECK (
        field_policy_revision > 0 AND authorization_revision > 0
    ),
    CONSTRAINT ck_prf_command_receipts_state CHECK (
        receipt_state IN (
            'ACCEPTED', 'RUNNING', 'SUCCEEDED', 'FAILED', 'RESULT_UNKNOWN', 'QUARANTINED'
        )
    ),
    CONSTRAINT ck_prf_command_receipts_completion CHECK (
        (receipt_state IN ('ACCEPTED', 'RUNNING', 'RESULT_UNKNOWN') AND completed_at IS NULL)
        OR
        (receipt_state IN ('SUCCEEDED', 'FAILED', 'QUARANTINED') AND completed_at IS NOT NULL)
    ),
    CONSTRAINT ck_prf_command_receipts_success_evidence CHECK (
        receipt_state <> 'SUCCEEDED'
        OR (applied_aggregate_version IS NOT NULL AND result_ref IS NOT NULL)
    )
);

CREATE TABLE hris_performance.prf_outbox_events (
    internal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL,
    tenant_id BIGINT NOT NULL,
    command_receipt_id UUID NOT NULL,
    aggregate_type VARCHAR(80) NOT NULL,
    aggregate_id UUID NOT NULL,
    aggregate_version BIGINT NOT NULL,
    event_type VARCHAR(160) NOT NULL,
    payload JSONB NOT NULL,
    delivery_state VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    delivery_attempts INTEGER NOT NULL DEFAULT 0,
    available_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_prf_outbox_events_tenant_id UNIQUE (tenant_id, event_id),
    CONSTRAINT uk_prf_outbox_events_aggregate_event UNIQUE (
        tenant_id, aggregate_id, aggregate_version, event_type
    ),
    CONSTRAINT fk_prf_outbox_events_receipt FOREIGN KEY (
        tenant_id, command_receipt_id
    ) REFERENCES hris_performance.prf_command_receipts (
        tenant_id, command_receipt_id
    ),
    CONSTRAINT ck_prf_outbox_events_version CHECK (aggregate_version > 0),
    CONSTRAINT ck_prf_outbox_events_payload_object CHECK (jsonb_typeof(payload) = 'object'),
    CONSTRAINT ck_prf_outbox_events_state CHECK (
        delivery_state IN ('PENDING', 'DELIVERED', 'QUARANTINED')
    ),
    CONSTRAINT ck_prf_outbox_events_attempts CHECK (delivery_attempts >= 0)
);

CREATE INDEX ix_prf_cycles_tenant_state
    ON hris_performance.prf_cycles (tenant_id, lifecycle_state, updated_at DESC);

CREATE INDEX ix_prf_cycle_versions_tenant_effective
    ON hris_performance.prf_cycle_versions (
        tenant_id, effective_from, effective_to, version_state
    );

CREATE INDEX ix_prf_population_previews_tenant_cycle
    ON hris_performance.prf_population_previews (
        tenant_id, cycle_version_id, created_at DESC
    );

CREATE INDEX ix_prf_command_receipts_tenant_state
    ON hris_performance.prf_command_receipts (tenant_id, receipt_state, accepted_at);

CREATE INDEX ix_prf_outbox_events_delivery
    ON hris_performance.prf_outbox_events (delivery_state, available_at, internal_id);

CREATE UNIQUE INDEX ux_prf_outbox_events_command_receipt
    ON hris_performance.prf_outbox_events (tenant_id, command_receipt_id);
