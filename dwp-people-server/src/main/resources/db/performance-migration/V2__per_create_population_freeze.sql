-- G7-LEASE-PER-PERFORMANCE-V2-R1 / BASE-TFR-PER-006
-- Immutable promotion of an existing participant preview. This migration does not
-- recompute, rewrite, or backfill a preview: only an explicit governed command may
-- create a freeze from a READY preview.

ALTER TABLE hris_performance.prf_population_preview_members
    ADD COLUMN created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;

-- Keep every preview as evidence, but permit only the latest row for a cycle version
-- to remain the current READY candidate.
WITH ranked AS (
    SELECT internal_id,
           ROW_NUMBER() OVER (
               PARTITION BY tenant_id, cycle_version_id
               ORDER BY created_at DESC, population_preview_id DESC
           ) AS ready_rank
      FROM hris_performance.prf_population_previews
     WHERE preview_state = 'READY'
)
UPDATE hris_performance.prf_population_previews preview
   SET preview_state = 'STALE'
  FROM ranked
 WHERE preview.internal_id = ranked.internal_id
   AND ranked.ready_rank > 1;

CREATE UNIQUE INDEX ux_prf_population_previews_current_ready
    ON hris_performance.prf_population_previews (tenant_id, cycle_version_id)
    WHERE preview_state = 'READY';

CREATE FUNCTION hris_performance.prf_serialize_population_preview()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.preview_state = 'READY' THEN
        PERFORM cycle_version_id
          FROM hris_performance.prf_cycle_versions
         WHERE tenant_id = NEW.tenant_id
           AND cycle_version_id = NEW.cycle_version_id
         FOR UPDATE;

        IF TG_OP = 'INSERT' THEN
            UPDATE hris_performance.prf_population_previews current
               SET preview_state = 'STALE'
             WHERE current.tenant_id = NEW.tenant_id
               AND current.cycle_version_id = NEW.cycle_version_id
               AND current.preview_state = 'READY'
               AND NOT (
                   current.population_rule_version_id = NEW.population_rule_version_id
                   AND current.source_cycle_aggregate_version = NEW.source_cycle_aggregate_version
                   AND current.workforce_snapshot_id = NEW.workforce_snapshot_id
                   AND current.workforce_snapshot_revision = NEW.workforce_snapshot_revision
               );
        ELSE
            UPDATE hris_performance.prf_population_previews current
               SET preview_state = 'STALE'
             WHERE current.tenant_id = NEW.tenant_id
               AND current.cycle_version_id = NEW.cycle_version_id
               AND current.preview_state = 'READY'
               AND current.internal_id <> OLD.internal_id
               AND NOT (
                   current.population_rule_version_id = NEW.population_rule_version_id
                   AND current.source_cycle_aggregate_version = NEW.source_cycle_aggregate_version
                   AND current.workforce_snapshot_id = NEW.workforce_snapshot_id
                   AND current.workforce_snapshot_revision = NEW.workforce_snapshot_revision
               );
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_prf_population_previews_serialize
    BEFORE INSERT OR UPDATE OF preview_state
    ON hris_performance.prf_population_previews
    FOR EACH ROW EXECUTE FUNCTION hris_performance.prf_serialize_population_preview();

