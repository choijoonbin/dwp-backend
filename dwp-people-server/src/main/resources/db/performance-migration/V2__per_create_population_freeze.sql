-- G7-LEASE-PER-PERFORMANCE-V2-R1 / BASE-TFR-PER-006
-- Immutable promotion of an existing participant preview. This migration does not
-- recompute, rewrite, or backfill a preview: only an explicit governed command may
-- create a freeze from a READY preview.

CREATE TABLE hris_performance.prf_population_freezes (
    internal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    population_freeze_id UUID NOT NULL,
    tenant_id BIGINT NOT NULL,
    cycle_id UUID NOT NULL,
    cycle_version_id UUID NOT NULL,
    population_preview_id UUID NOT NULL,
    population_rule_version_id UUID NOT NULL,
    workforce_snapshot_id UUID NOT NULL,
    workforce_snapshot_revision BIGINT NOT NULL,
    source_cycle_aggregate_version BIGINT NOT NULL,
    freeze_state VARCHAR(20) NOT NULL,
    participant_count INTEGER NOT NULL,
    reviewer_assignment_count INTEGER NOT NULL,
    content_hash CHAR(64) NOT NULL,
    aggregate_version BIGINT NOT NULL,
    command_receipt_id UUID NOT NULL,
    frozen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    frozen_by BIGINT NOT NULL,
    CONSTRAINT uk_prf_population_freezes_tenant_id UNIQUE (
        tenant_id, population_freeze_id
    ),
    CONSTRAINT uk_prf_population_freezes_cycle_version UNIQUE (
        tenant_id, cycle_version_id
    ),
    CONSTRAINT uk_prf_population_freezes_preview UNIQUE (
        tenant_id, population_preview_id
    ),
    CONSTRAINT uk_prf_population_freezes_receipt UNIQUE (
        tenant_id, command_receipt_id
    ),
    CONSTRAINT fk_prf_population_freezes_cycle FOREIGN KEY (
        tenant_id, cycle_id
    ) REFERENCES hris_performance.prf_cycles (tenant_id, cycle_id),
    CONSTRAINT fk_prf_population_freezes_cycle_version FOREIGN KEY (
        tenant_id, cycle_version_id
    ) REFERENCES hris_performance.prf_cycle_versions (tenant_id, cycle_version_id),
    CONSTRAINT fk_prf_population_freezes_preview FOREIGN KEY (
        tenant_id, population_preview_id
    ) REFERENCES hris_performance.prf_population_previews (
        tenant_id, population_preview_id
    ),
    CONSTRAINT fk_prf_population_freezes_receipt FOREIGN KEY (
        tenant_id, command_receipt_id
    ) REFERENCES hris_performance.prf_command_receipts (
        tenant_id, command_receipt_id
    ),
    CONSTRAINT ck_prf_population_freezes_state CHECK (freeze_state = 'FROZEN'),
    CONSTRAINT ck_prf_population_freezes_counts CHECK (
        participant_count >= 0 AND reviewer_assignment_count >= 0
    ),
    CONSTRAINT ck_prf_population_freezes_revisions CHECK (
        workforce_snapshot_revision > 0
        AND source_cycle_aggregate_version >= 0
        AND aggregate_version = 1
    ),
    CONSTRAINT ck_prf_population_freezes_hash CHECK (
        content_hash ~ '^[0-9a-f]{64}$'
    )
);

CREATE TABLE hris_performance.prf_population_freeze_members (
    internal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    population_freeze_id UUID NOT NULL,
    participant_ref UUID NOT NULL,
    primary_assignment_ref UUID NOT NULL,
    workforce_status VARCHAR(24) NOT NULL,
    organization_ref UUID NOT NULL,
    reviewer_assignment_ref UUID,
    job_profile_ref UUID,
    grade_ref UUID,
    eligibility_code VARCHAR(40) NOT NULL,
    frozen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_prf_population_freeze_members_identity UNIQUE (
        tenant_id, population_freeze_id, participant_ref, primary_assignment_ref
    ),
    CONSTRAINT fk_prf_population_freeze_members_freeze FOREIGN KEY (
        tenant_id, population_freeze_id
    ) REFERENCES hris_performance.prf_population_freezes (
        tenant_id, population_freeze_id
    ),
    CONSTRAINT ck_prf_population_freeze_members_status CHECK (
        workforce_status IN ('PENDING', 'ACTIVE', 'INACTIVE', 'TERMINATED')
    ),
    CONSTRAINT ck_prf_population_freeze_members_eligibility CHECK (
        eligibility_code IN ('INCLUDED', 'EXCLUDED', 'REVIEW_REQUIRED')
    )
);

CREATE TABLE hris_performance.prf_population_freeze_reviewers (
    internal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    population_freeze_id UUID NOT NULL,
    reviewer_assignment_ref UUID NOT NULL,
    frozen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_prf_population_freeze_reviewers_identity UNIQUE (
        tenant_id, population_freeze_id, reviewer_assignment_ref
    ),
    CONSTRAINT fk_prf_population_freeze_reviewers_freeze FOREIGN KEY (
        tenant_id, population_freeze_id
    ) REFERENCES hris_performance.prf_population_freezes (
        tenant_id, population_freeze_id
    )
);

CREATE INDEX ix_prf_population_freezes_tenant_cycle
    ON hris_performance.prf_population_freezes (
        tenant_id, cycle_id, frozen_at DESC
    );

CREATE INDEX ix_prf_population_freeze_members_participant
    ON hris_performance.prf_population_freeze_members (
        tenant_id, participant_ref, population_freeze_id
    );

CREATE INDEX ix_prf_population_freeze_reviewers_assignment
    ON hris_performance.prf_population_freeze_reviewers (
        tenant_id, reviewer_assignment_ref, population_freeze_id
    );

CREATE FUNCTION hris_performance.prf_reject_population_freeze_mutation()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'PER_POPULATION_FREEZE_IMMUTABLE'
        USING ERRCODE = '55000';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_prf_population_freezes_immutable
    BEFORE UPDATE OR DELETE ON hris_performance.prf_population_freezes
    FOR EACH ROW EXECUTE FUNCTION hris_performance.prf_reject_population_freeze_mutation();

CREATE TRIGGER trg_prf_population_freeze_members_immutable
    BEFORE UPDATE OR DELETE ON hris_performance.prf_population_freeze_members
    FOR EACH ROW EXECUTE FUNCTION hris_performance.prf_reject_population_freeze_mutation();

CREATE TRIGGER trg_prf_population_freeze_reviewers_immutable
    BEFORE UPDATE OR DELETE ON hris_performance.prf_population_freeze_reviewers
    FOR EACH ROW EXECUTE FUNCTION hris_performance.prf_reject_population_freeze_mutation();

ALTER TABLE hris_performance.prf_population_freezes ENABLE ROW LEVEL SECURITY;
ALTER TABLE hris_performance.prf_population_freeze_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE hris_performance.prf_population_freeze_reviewers ENABLE ROW LEVEL SECURITY;

