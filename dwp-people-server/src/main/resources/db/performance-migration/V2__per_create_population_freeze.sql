CREATE FUNCTION hris_performance.prf_capture_review_operation(
    captured_tenant_id BIGINT,
    captured_cycle_id UUID
)
RETURNS VOID AS $$
BEGIN
    PERFORM set_config('dwp.tenant_id', captured_tenant_id::TEXT, TRUE);
    INSERT INTO hris_performance.prf_review_operation_history (
        tenant_id, cycle_id, display_name, lifecycle_state, aggregate_version,
        cycle_version_id, population_rule_version_id, effective_from, effective_to,
        population_preview_id, preview_state, participant_count,
        preview_created_at, preview_expires_at, population_freeze_id)
    SELECT cycle.tenant_id, cycle.cycle_id, cycle.display_name,
           cycle.lifecycle_state, cycle.aggregate_version,
           version.cycle_version_id, version.population_rule_version_id,
           version.effective_from, version.effective_to,
           preview.population_preview_id, preview.preview_state,
           preview.participant_count, preview.created_at, preview.expires_at,
           frozen_population.population_freeze_id
      FROM hris_performance.prf_cycles cycle
      LEFT JOIN hris_performance.prf_cycle_versions version
        ON version.tenant_id = cycle.tenant_id
       AND version.cycle_id = cycle.cycle_id
       AND version.version_no = cycle.active_version_no
      LEFT JOIN LATERAL (
          SELECT candidate.population_preview_id, candidate.preview_state,
                 candidate.participant_count, candidate.created_at,
                 candidate.expires_at
            FROM hris_performance.prf_population_previews candidate
           WHERE candidate.tenant_id = cycle.tenant_id
             AND candidate.cycle_version_id = version.cycle_version_id
           ORDER BY candidate.created_at DESC,
                    candidate.population_preview_id DESC
           LIMIT 1
      ) preview ON TRUE
      LEFT JOIN LATERAL (
          SELECT candidate.population_freeze_id
            FROM hris_performance.prf_population_freezes candidate
           WHERE candidate.tenant_id = cycle.tenant_id
             AND candidate.cycle_version_id = version.cycle_version_id
           ORDER BY candidate.frozen_at DESC,
                    candidate.population_freeze_id DESC
           LIMIT 1
      ) frozen_population ON TRUE
     WHERE cycle.tenant_id = captured_tenant_id
       AND cycle.cycle_id = captured_cycle_id;
END;
$$ LANGUAGE plpgsql;

CREATE FUNCTION hris_performance.prf_capture_review_operation_trigger()
RETURNS TRIGGER AS $$
DECLARE
    target_tenant_id BIGINT;
    target_cycle_id UUID;
BEGIN
    target_tenant_id := NEW.tenant_id;
    IF TG_TABLE_NAME = 'prf_cycles' THEN
        target_cycle_id := NEW.cycle_id;
    ELSIF TG_TABLE_NAME = 'prf_cycle_versions' THEN
        target_cycle_id := NEW.cycle_id;
    ELSIF TG_TABLE_NAME = 'prf_population_freezes' THEN
        target_cycle_id := NEW.cycle_id;
    ELSE
        SELECT cycle_id INTO target_cycle_id
          FROM hris_performance.prf_cycle_versions
         WHERE tenant_id = NEW.tenant_id
           AND cycle_version_id = NEW.cycle_version_id;
    END IF;
    PERFORM hris_performance.prf_capture_review_operation(
        target_tenant_id, target_cycle_id);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

